
# ==============================================================================
# SCRIPT 07: OSCG / OMA-INFORMED INTEGRIN BINDING-AFFINITY COMPARISONS
# ==============================================================================
#
# PROJECT:
# Comparative Structural Analysis of RGD-Binding Integrins and Their Ability
# to Bind Thyroid Hormones
#
# PURPOSE:
# Reproduce two analyses of integrin heterodimers containing OMA-related
# alpha or beta subunits across three species:
#
#   Homo sapiens (HS)
#   Strongylocentrotus purpuratus (SP)
#   Nematostella vectensis (NV)
#
# FIGURE 17:
#   Compare receptor-level predicted binding affinities within six
#   OMA-supported comparison groups (OSCG 1 through OSCG 6).
#
#   Three ligand categories are examined:
#     T3/T4
#     T4AM
#     TRIAC/TETRAC
#
# FIGURE 18:
#   Compare species-specific median raw KD values for nine ligands
#   within corresponding OSCGs using six scatterplots.
#
#   Spearman rank correlations quantify similarities between the
#   predicted ligand-binding profiles of each species pair.
#
# ------------------------------------------------------------------------------
# INPUT FILES
# ------------------------------------------------------------------------------
#
# All inputs are generated by Script 02:
#
# Results/02_Prepare_Integrin_BindingData_RESULTS/
#
#   C9_OMA_Annotated_Receptor_Binding_Table.csv
#   Receptor_Metadata_OMA.csv
#   BindingAffinity_NegLog10KD_Wide.csv
#   BindingAffinity_RawKD_Long.csv
#
# ------------------------------------------------------------------------------
# BINDING-AFFINITY REPRESENTATIONS
# ------------------------------------------------------------------------------
#
# FIGURE 17:
#
#   Uses predicted -log10(KD), where higher values indicate stronger
#   predicted binding.
#
#   T3/T4 and TRIAC/TETRAC are arithmetic means of the corresponding
#   two -log10(KD) values WITHIN EACH individual receptor model.
#
#   T4AM represents the individual receptor's predicted affinity.
#
# FIGURE 18:
#
#   Uses the original RAW KD values in molar units.
#
#   Median KD is calculated separately for each species, OSCG and ligand.
#
#   Lower KD indicates stronger predicted binding.
#
#   Median raw KD must not be calculated by back-transforming the median
#   -log10(KD), because the two calculations can differ for groups with
#   an even number of receptor models.
#
# ------------------------------------------------------------------------------
# OMA-SUPPORTED COMPARISON GROUPS
# ------------------------------------------------------------------------------
#
#   OSCG 1: alpha3/alpha6/alpha7-related (NV)
#   OSCG 2: alpha4/alpha9-related        (SP)
#   OSCG 3: alpha6/alpha7-related        (SP)
#   OSCG 4: alphaV/alpha5/alpha8-related (HS and SP)
#   OSCG 5: beta1-related               (HS, SP, NV)
#   OSCG 6: beta6-related               (HS and NV)
#
# OMA relationships apply to INDIVIDUAL alpha or beta subunits.
# These classifications do not establish orthology of entire
# alpha-beta integrin heterodimers.
#
# ------------------------------------------------------------------------------
# FIGURE 18 COMPARISONS
# ------------------------------------------------------------------------------
#
#   A: SP vs NV - OSCG 1 and OSCG 3 (alpha6/alpha7)
#   B: SP vs HS - OSCG 4 (alphaV/alpha5/alpha8)
#   C: NV vs HS - OSCG 5 (beta1)
#   D: SP vs HS - OSCG 5 (beta1)
#   E: SP vs NV - OSCG 5 (beta1)
#   F: NV vs HS - OSCG 6 (beta6)
#
# ------------------------------------------------------------------------------
# STATISTICAL INTERPRETATION
# ------------------------------------------------------------------------------
#
# Figure 17 provides descriptive comparisons of individual computational
# receptor models.
#
# Figure 18 calculates Spearman rho from nine paired ligand medians.
#
# No biological replicate hypothesis tests are performed.
#
# All affinities are computational predictions rather than experimentally
# measured dissociation constants.
#
# ------------------------------------------------------------------------------
# THESIS REFERENCES
# ------------------------------------------------------------------------------
#
# Results Section 3.8: Figure 17
# Results Section 3.9: Figure 18
# Results Section 3.1.2: OMA group definitions
#
# WORKING DIRECTORY:
# Manually set the working directory to R_Scripts.
# This script does not call setwd().
#
# OUTPUT DIRECTORY:
# Results/07_OMA_BindingAffinity_Comparisons_RESULTS/
# ==============================================================================


# ==============================================================================
# 0. INPUT/OUTPUT PATHS AND REQUIRED R PACKAGES
# ==============================================================================

# Read the standardized binding-affinity and OMA data prepared by Script 02.
# The original Excel workbooks do not need to be imported again.

INPUT_DIR <- file.path(
  "Results",
  "02_Prepare_Integrin_BindingData_RESULTS"
)

OUTPUT_DIR <- file.path(
  "Results",
  "07_OMA_BindingAffinity_Comparisons_RESULTS"
)

# Create the results folder automatically.

dir.create(
  OUTPUT_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

# Define the four input files.

INPUT_C9 <- file.path(
  INPUT_DIR,
  "C9_OMA_Annotated_Receptor_Binding_Table.csv"
)

INPUT_METADATA <- file.path(
  INPUT_DIR,
  "Receptor_Metadata_OMA.csv"
)

INPUT_SCORES <- file.path(
  INPUT_DIR,
  "BindingAffinity_NegLog10KD_Wide.csv"
)

INPUT_RAW_KD <- file.path(
  INPUT_DIR,
  "BindingAffinity_RawKD_Long.csv"
)

# Stop if an input file does not exist.

for (path in c(INPUT_C9, INPUT_METADATA, INPUT_SCORES, INPUT_RAW_KD)) {
  
  if (!file.exists(path)) {
    stop("Missing input file: ", path, "\nRun Script 02 first.")
  }
  
}


# Required packages:
#
# ggplot2:  Generate Figures 17 and 18.
# dplyr:    Filter, join and summarize receptor data.
# tidyr:    Convert between wide and long data formats.
# ggrepel:  Reduce overlapping ligand labels in Figure 18.
# patchwork: Combine the Figure 18 panels.
# scales:   Format logarithmic KD axis labels.

required_packages <- c(
  "ggplot2",
  "dplyr",
  "tidyr",
  "ggrepel",
  "patchwork",
  "scales"
)

missing_packages <- setdiff(
  required_packages,
  rownames(installed.packages())
)

if (length(missing_packages) > 0L) {
  
  stop(
    "Install these packages before running Script 07: ",
    paste(missing_packages, collapse = ", "),
    "\nUse install.packages(c(\"ggplot2\", \"dplyr\", \"tidyr\", ",
    "\"ggrepel\", \"patchwork\", \"scales\"))"
  )
  
}

suppressPackageStartupMessages({
  
  library(ggplot2)
  library(dplyr)
  library(tidyr)
  library(ggrepel)
  library(patchwork)
  
})


# Preserve the same nine ligands used by the preceding analysis scripts.

LIGANDS <- c(
  "Cilengitide",
  "T3",
  "T4",
  "TRIAC",
  "TETRAC",
  "sT3",
  "sT4",
  "rT3",
  "T4AM"
)

# Species order matches the latest Figure 17 script.

SPECIES <- c(
  "H. sapiens",
  "N. vectensis",
  "S. purpuratus"
)

EXPECTED_COUNTS <- c(
  "H. sapiens" = 8L,
  "N. vectensis" = 16L,
  "S. purpuratus" = 24L
)

# Export CSV files without an unnecessary row-number column.

write_table <- function(x, filename) {
  
  utils::write.csv(
    x,
    file.path(OUTPUT_DIR, filename),
    row.names = FALSE,
    na = ""
  )
  
}


# ==============================================================================
# 1. IMPORT AND CROSS-VALIDATE THE PREPARED RECEPTOR DATA
# ==============================================================================

# The C9 table contains:
#
#   - Receptor identifiers
#   - Species assignments
#   - Alpha and beta OMA group classifications
#   - T3/T4 mean affinity
#   - T4AM affinity
#   - TRIAC/TETRAC mean affinity
#
# The other files provide independently prepared metadata,
# transformed affinity scores and original raw KD values.

c9 <- utils::read.csv(
  INPUT_C9,
  check.names = FALSE,
  stringsAsFactors = FALSE
)

metadata <- utils::read.csv(
  INPUT_METADATA,
  check.names = FALSE,
  stringsAsFactors = FALSE
)

scores <- utils::read.csv(
  INPUT_SCORES,
  check.names = FALSE,
  stringsAsFactors = FALSE
)

raw_kd <- utils::read.csv(
  INPUT_RAW_KD,
  check.names = FALSE,
  stringsAsFactors = FALSE
)


# ------------------------------------------------------------------------------
# 1.1 VALIDATE COLUMN NAMES AND DATASET DIMENSIONS
# ------------------------------------------------------------------------------

required_c9 <- c(
  "Receptor",
  "Species",
  "AlphaGroup",
  "BetaGroup",
  "T3_T4",
  "T4AM",
  "TRIAC_TETRAC"
)

required_meta <- c(
  "Receptor",
  "Species",
  "AlphaGroup",
  "BetaGroup"
)

required_raw <- c(
  "Receptor",
  "Species",
  "Ligand",
  "KD_M"
)

if (
  !all(required_c9 %in% names(c9)) ||
  !all(required_meta %in% names(metadata)) ||
  !all(required_raw %in% names(raw_kd)) ||
  !identical(names(scores), c("Receptor", LIGANDS))
) {
  
  stop(
    "One or more Script 02 inputs have missing or unexpected column names."
  )
  
}


# Confirm that each wide-format table contains 48 uniquely identified
# receptor models.

for (dat in list(c9, metadata, scores)) {
  
  if (
    nrow(dat) != 48L ||
    anyNA(dat$Receptor) ||
    any(!nzchar(dat$Receptor)) ||
    anyDuplicated(dat$Receptor)
  ) {
    
    stop(
      "Expected 48 uniquely identified receptors in every wide input."
    )
    
  }
  
}


# Confirm that receptor identifiers agree across the prepared tables.

if (
  !setequal(c9$Receptor, scores$Receptor) ||
  !setequal(c9$Receptor, metadata$Receptor)
) {
  
  stop(
    "Receptor identifiers disagree between Script 02 outputs."
  )
  
}


# Match records by receptor identity rather than relying on row positions.

metadata <- metadata[
  match(c9$Receptor, metadata$Receptor),
  ,
  drop = FALSE
]

scores <- scores[
  match(c9$Receptor, scores$Receptor),
  ,
  drop = FALSE
]


# ------------------------------------------------------------------------------
# 1.2 VALIDATE SPECIES AND OMA GROUP ASSIGNMENTS
# ------------------------------------------------------------------------------

# Ensure each receptor has the same species and OMA classifications
# in both prepared metadata files.

if (
  !identical(c9$Species, metadata$Species) ||
  !identical(c9$AlphaGroup, metadata$AlphaGroup) ||
  !identical(c9$BetaGroup, metadata$BetaGroup)
) {
  
  stop(
    "OMA grouping or species assignments disagree between prepared files."
  )
  
}

if (
  !identical(
    as.integer(table(factor(c9$Species, levels = SPECIES))),
    as.integer(EXPECTED_COUNTS[SPECIES])
  )
) {
  
  stop(
    "Expected 8 human, 16 sea-anemone, and 24 sea-urchin receptor models."
  )
  
}


# ------------------------------------------------------------------------------
# 1.3 VALIDATE TRANSFORMED AFFINITY SCORES
# ------------------------------------------------------------------------------

# Figure 17 uses -log10(KD) values.
#
# Confirm all ligand columns are numeric and finite.

if (
  !all(vapply(
    scores[, LIGANDS, drop = FALSE],
    is.numeric,
    logical(1)
  )) ||
  !all(vapply(
    c9[, c("T3_T4", "T4AM", "TRIAC_TETRAC"), drop = FALSE],
    is.numeric,
    logical(1)
  ))
) {
  
  stop(
    "Binding-affinity scores must be numeric."
  )
  
}

score_matrix <- as.matrix(
  scores[, LIGANDS, drop = FALSE]
)

rownames(score_matrix) <- scores$Receptor

storage.mode(score_matrix) <- "double"

if (any(!is.finite(score_matrix))) {
  
  stop(
    "Non-finite -log10(KD) values in the prepared score matrix."
  )
  
}


# ------------------------------------------------------------------------------
# 1.4 CHECK RECEPTOR-LEVEL LIGAND-GROUP SCORES
# ------------------------------------------------------------------------------

# The scores used for Figure 17 should be calculated as follows:
#
# T3_T4:
#   Mean of T3 and T4 transformed affinities for each receptor.
#
# T4AM:
#   Individual receptor's T4AM transformed affinity.
#
# TRIAC_TETRAC:
#   Mean of TRIAC and TETRAC transformed affinities for each receptor.
#
# Verify the precomputed C9 values against the original 48 x 9 matrix.

expected_group_scores <- cbind(
  
  T3_T4 = rowMeans(
    score_matrix[, c("T3", "T4"), drop = FALSE]
  ),
  
  T4AM = score_matrix[, "T4AM"],
  
  TRIAC_TETRAC = rowMeans(
    score_matrix[, c("TRIAC", "TETRAC"), drop = FALSE]
  )
  
)

observed_group_scores <- as.matrix(
  c9[, colnames(expected_group_scores), drop = FALSE]
)

if (
  any(!is.finite(observed_group_scores)) ||
  max(abs(
    observed_group_scores - expected_group_scores
  )) > 1e-8
) {
  
  stop(
    "C9 ligand-group scores disagree with original -log10(KD) inputs."
  )
  
}


# ------------------------------------------------------------------------------
# 1.5 VALIDATE ORIGINAL RAW KD VALUES
# ------------------------------------------------------------------------------

# Figure 18 requires the original KD values in molar units.
#
# The dataset must contain:
#
#   48 receptor models x 9 ligands = 432 measurements
#
# Every KD must be strictly positive for logarithmic plotting.

if (
  nrow(raw_kd) != 432L ||
  anyNA(raw_kd[, required_raw]) ||
  !is.numeric(raw_kd$KD_M) ||
  any(!is.finite(raw_kd$KD_M)) ||
  any(raw_kd$KD_M <= 0) ||
  anyDuplicated(raw_kd[, c("Receptor", "Ligand")]) ||
  !setequal(raw_kd$Receptor, c9$Receptor) ||
  !setequal(raw_kd$Ligand, LIGANDS)
) {
  
  stop(
    "Raw KD table must contain 432 unique, positive receptor-ligand KDs."
  )
  
}


# Recalculate -log10(KD) for every raw value to confirm that the raw
# and transformed tables refer to the same binding predictions.

score_rows <- match(
  raw_kd$Receptor,
  rownames(score_matrix)
)

score_cols <- match(
  raw_kd$Ligand,
  colnames(score_matrix)
)

if (anyNA(score_rows) || anyNA(score_cols)) {
  
  stop(
    "A raw KD receptor or ligand did not match the score matrix."
  )
  
}

expected_log_scores <- score_matrix[
  cbind(score_rows, score_cols)
]

max_raw_log_difference <- max(
  abs(
    -log10(raw_kd$KD_M) - expected_log_scores
  )
)

if (max_raw_log_difference > 1e-8) {
  
  stop(
    "Raw KD and -log10(KD) data disagree; maximum difference: ",
    signif(max_raw_log_difference, 8)
  )
  
}


# ------------------------------------------------------------------------------
# 1.6 ATTACH OMA METADATA TO RAW KD MEASUREMENTS
# ------------------------------------------------------------------------------

# Each raw receptor-ligand prediction is joined to the appropriate
# receptor's OMA alpha- and beta-subunit classifications.
#
# Joining by both receptor and species prevents accidental mismatches.

raw_oma <- raw_kd %>%
  
  left_join(
    
    metadata %>%
      select(
        Receptor,
        Species,
        AlphaGroup,
        BetaGroup
      ),
    
    by = c(
      "Receptor",
      "Species"
    )
  )

if (
  nrow(raw_oma) != 432L ||
  anyNA(raw_oma$AlphaGroup) ||
  anyNA(raw_oma$BetaGroup)
) {
  
  stop(
    "Some raw KD records could not be matched to their OMA annotations."
  )
  
}

message(
  "Validated 48 receptor models, 432 raw KD measurements, and ",
  "the three receptor-level Figure 17 affinity variables."
)


# ==============================================================================
# 2. DEFINE THE SIX OMA-SUPPORTED COMPARISON GROUPS (OSCGs)
# ==============================================================================

# These OSCG classifications reproduce the latest Figure 17 analysis.
#
# OSCG 1 and OSCG 3 are treated as separate groups in Figure 17,
# but their overlapping alpha6/alpha7-related relationships form
# a cross-species comparison in Figure 18A.
#
# The group identifiers refer to curated OMA-supported comparison
# categories rather than direct identifiers of OMA orthologous groups.

group_key <- data.frame(
  
  GroupLabel = paste(
    "OSCG",
    1:6
  ),
  
  GroupType = c(
    rep("Alpha-based", 4),
    rep("Beta-based", 2)
  ),
  
  OriginalGroup = c(
    "alpha3_6_7_related",
    "alpha4_9_related",
    "alpha6_7_related",
    "alphaV_5_8_related",
    "beta1_related",
    "beta6_related"
  ),
  
  CaptionMeaning = c(
    "Receptors containing alpha subunits in the alpha3/alpha6/alpha7-related OMA-supported relationship",
    "Receptors containing alpha subunits in the alpha4/alpha9-related OMA-supported relationship",
    "Receptors containing alpha subunits in the alpha6/alpha7-related OMA-supported relationship",
    "Receptors containing alpha subunits in the alphaV/alpha5/alpha8-related OMA-supported relationship",
    "Receptors containing beta subunits in the beta1-related OMA-supported relationship",
    "Receptors containing beta subunits in the beta6-related OMA-supported relationship"
  ),
  
  stringsAsFactors = FALSE
  
)


# Save a numerical group key for researchers interpreting Figures 17 and 18.

write_table(
  group_key,
  "Figure17_OSCG_Key.csv"
)


# ==============================================================================
# 3. PREPARE RECEPTOR-LEVEL AFFINITY DATA FOR FIGURE 17
# ==============================================================================

# Each included receptor contributes three ligand-category scores:
#
#   T3_T4
#   T4AM
#   TRIAC_TETRAC
#
# A receptor may be included in one alpha-related OSCG and one beta-related
# OSCG because its alpha and beta subunits are classified independently.
#
# All scores are preserved at the individual receptor level.


# ------------------------------------------------------------------------------
# 3.1 PREPARE ALPHA-RELATED GROUPS
# ------------------------------------------------------------------------------

alpha_points <- c9 %>%
  
  filter(
    AlphaGroup %in% group_key$OriginalGroup[1:4]
  ) %>%
  
  select(
    Receptor,
    Species,
    AlphaGroup,
    T3_T4,
    T4AM,
    TRIAC_TETRAC
  ) %>%
  
  pivot_longer(
    cols = c(T3_T4, T4AM, TRIAC_TETRAC),
    names_to = "LigandGroup",
    values_to = "Affinity"
  ) %>%
  
  rename(
    OriginalGroup = AlphaGroup
  ) %>%
  
  mutate(
    GroupType = "Alpha-based"
  )


# ------------------------------------------------------------------------------
# 3.2 PREPARE BETA-RELATED GROUPS
# ------------------------------------------------------------------------------

beta_points <- c9 %>%
  
  filter(
    BetaGroup %in% group_key$OriginalGroup[5:6]
  ) %>%
  
  select(
    Receptor,
    Species,
    BetaGroup,
    T3_T4,
    T4AM,
    TRIAC_TETRAC
  ) %>%
  
  pivot_longer(
    cols = c(T3_T4, T4AM, TRIAC_TETRAC),
    names_to = "LigandGroup",
    values_to = "Affinity"
  ) %>%
  
  rename(
    OriginalGroup = BetaGroup
  ) %>%
  
  mutate(
    GroupType = "Beta-based"
  )


# ------------------------------------------------------------------------------
# 3.3 COMBINE ALPHA AND BETA GROUPS
# ------------------------------------------------------------------------------

fig17_points <- bind_rows(
  alpha_points,
  beta_points
) %>%
  
  left_join(
    
    group_key %>%
      select(
        GroupLabel,
        GroupType,
        OriginalGroup
      ),
    
    by = c(
      "GroupType",
      "OriginalGroup"
    )
  )


# With the current 48-receptor dataset, there are 73 receptor/group
# memberships, each contributing three ligand-category scores.
#
# Therefore, the combined table contains 219 plotted records.

if (
  nrow(fig17_points) != 219L ||
  anyNA(fig17_points$GroupLabel) ||
  any(!is.finite(fig17_points$Affinity))
) {
  
  stop(
    "Unexpected Figure 17 point count or missing OSCG assignments."
  )
  
}


# ------------------------------------------------------------------------------
# 3.4 EXPORT INDIVIDUAL RECEPTOR SCORES
# ------------------------------------------------------------------------------

# Preserve the original receptor identities and unrounded affinity values.
#
# These allow the grouped figure to be independently reconstructed.

write_table(
  
  fig17_points %>%
    select(
      GroupLabel,
      GroupType,
      OriginalGroup,
      Receptor,
      Species,
      LigandGroup,
      Affinity
    ),
  
  "Figure17_OSCG_IndividualReceptor_Affinities.csv"
  
)


# ------------------------------------------------------------------------------
# 3.5 CALCULATE GROUP-LEVEL DESCRIPTIVE STATISTICS
# ------------------------------------------------------------------------------

# For every OSCG, species and ligand category, calculate:
#
#   Number of contributing receptor models
#   Mean
#   Median
#   Standard deviation
#   Minimum
#   Maximum
#
# These describe computational receptor models, not independent
# biological samples.

fig17_summary <- fig17_points %>%
  
  group_by(
    GroupLabel,
    GroupType,
    OriginalGroup,
    Species,
    LigandGroup
  ) %>%
  
  summarise(
    
    N_Receptors = n_distinct(Receptor),
    
    Mean_NegLog10KD = mean(Affinity),
    
    Median_NegLog10KD = median(Affinity),
    
    SD_NegLog10KD = if (n() > 1L) {
      sd(Affinity)
    } else {
      NA_real_
    },
    
    Min_NegLog10KD = min(Affinity),
    
    Max_NegLog10KD = max(Affinity),
    
    .groups = "drop"
  )

write_table(
  fig17_summary,
  "Figure17_OSCG_GroupSpecies_AffinitySummary.csv"
)


# ==============================================================================
# 4. GENERATE FIGURE 17: SIX OSCGs x THREE LIGAND CATEGORIES
# ==============================================================================

# Preserve the updated Figure 17 layout:
#
#   Six rows:
#     OSCG 1 to OSCG 6
#
#   Three columns:
#     T3/T4, T4AM, TRIAC/TETRAC
#
#   Horizontal axis:
#     H. sapiens, N. vectensis, S. purpuratus
#
#   Vertical axis:
#     Predicted -log10(KD)
#
# Individual receptors are represented by points.
#
# Small horizontal jitter offsets overlapping points without modifying
# their predicted affinity values.


# ------------------------------------------------------------------------------
# 4.1 DEFINE THE DISPLAY ORDER AND LABELS
# ------------------------------------------------------------------------------

fig17_plot <- fig17_points

fig17_plot$Species <- factor(
  fig17_plot$Species,
  levels = SPECIES
)

fig17_plot$GroupLabel <- factor(
  fig17_plot$GroupLabel,
  levels = group_key$GroupLabel
)

# Retain the original variable names for statistics and CSV exports,
# but use reader-friendly labels for the figure.

fig17_plot$LigandGroup <- factor(
  fig17_plot$LigandGroup,
  
  levels = c(
    "T3_T4",
    "T4AM",
    "TRIAC_TETRAC"
  ),
  
  labels = c(
    "T3/T4",
    "T4AM",
    "TRIAC/TETRAC"
  )
)


# ------------------------------------------------------------------------------
# 4.2 DEFINE THE UPDATED FIGURE 17 SPECIES COLOURS
# ------------------------------------------------------------------------------

species_colours <- c(
  "H. sapiens" = "#56B4C9",
  "N. vectensis" = "#43A047",
  "S. purpuratus" = "#B05CC6"
)


# ------------------------------------------------------------------------------
# 4.3 CREATE THE COMBINED SIX-GROUP FIGURE
# ------------------------------------------------------------------------------

figure17 <- ggplot(
  
  fig17_plot,
  
  aes(
    x = Species,
    y = Affinity,
    colour = Species
  )
  
) +
  
  geom_jitter(
    position = position_jitter(
      width = 0.15,
      height = 0,
      seed = 123
    ),
    size = 2.5,
    alpha = 0.8
  ) +
  
  facet_grid(
    GroupLabel ~ LigandGroup,
    scales = "free_y"
  ) +
  
  scale_colour_manual(
    values = species_colours
  ) +
  
  labs(
    title = "Binding affinities within OMA-supported comparison groups",
    x = NULL,
    y = expression(-log[10](K[D])),
    colour = "Species"
  ) +
  
  theme_bw() +
  
  theme(
    
    axis.text.x = element_text(
      angle = 30,
      hjust = 1
    ),
    
    strip.text = element_text(
      face = "bold",
      size = 11
    ),
    
    plot.title = element_text(
      face = "bold",
      hjust = 0.5
    ),
    
    legend.position = "right"
    
  )


# ------------------------------------------------------------------------------
# 4.4 EXPORT FIGURE 17
# ------------------------------------------------------------------------------

ggsave(
  file.path(
    OUTPUT_DIR,
    "Figure17_OSCG_BindingComparison.pdf"
  ),
  
  figure17,
  
  width = 12,
  height = 16,
  units = "in"
)

ggsave(
  file.path(
    OUTPUT_DIR,
    "Figure17_OSCG_BindingComparison.png"
  ),
  
  figure17,
  
  width = 12,
  height = 16,
  units = "in",
  dpi = 300,
  bg = "white"
)

message(
  "Saved Figure 17 and its OSCG receptor-level data and summaries."
)


# ==============================================================================
# 5. DEFINE COMPARABLE OMA GROUPS FOR FIGURE 18
# ==============================================================================

# Figure 18 compares OSCG-related receptor subsets across species.
#
# Alpha-related comparisons:
#
#   OSCG 1 + OSCG 3:
#     alpha6/alpha7-overlap, NV vs SP
#
#   OSCG 4:
#     alphaV/alpha5/alpha8-related, HS vs SP
#
# Beta-related comparisons:
#
#   OSCG 5:
#     beta1-related, all three species
#
#   OSCG 6:
#     beta6-related, HS vs NV
#
# These definitions reproduce the updated Figure 18 analysis.

raw_oma <- raw_oma %>%
  
  mutate(
    
    AlphaComparisonGroup = case_when(
      
      Species == "N. vectensis" &
        AlphaGroup == "alpha3_6_7_related" ~
        "alpha6/alpha7-overlap",
      
      Species == "S. purpuratus" &
        AlphaGroup == "alpha6_7_related" ~
        "alpha6/alpha7-overlap",
      
      Species %in% c(
        "H. sapiens",
        "S. purpuratus"
      ) &
        AlphaGroup == "alphaV_5_8_related" ~
        "alphaV/alpha5/alpha8-related",
      
      TRUE ~ NA_character_
      
    ),
    
    BetaComparisonGroup = case_when(
      
      BetaGroup == "beta1_related" ~
        "beta1-related",
      
      BetaGroup == "beta6_related" ~
        "beta6-related",
      
      TRUE ~ NA_character_
      
    )
    
  )


# ==============================================================================
# 6. CALCULATE MEDIAN RAW KD BY OSCG, SPECIES AND LIGAND
# ==============================================================================

# Figure 18 uses medians of original RAW KD values in molar units.
#
# For each OSCG comparison group, species and ligand:
#
#   1. Extract the original KD measurements from the relevant receptors.
#   2. Calculate the median of those raw KD values.
#   3. Preserve the number of receptor models contributing to the median.
#
# The calculation is performed before any logarithmic axis transformation.
#
# These medians must not be derived from transformed -log10(KD) scores.


# ------------------------------------------------------------------------------
# 6.1 CALCULATE ALPHA-GROUP MEDIANS
# ------------------------------------------------------------------------------

alpha_medians <- raw_oma %>%
  
  filter(
    !is.na(AlphaComparisonGroup)
  ) %>%
  
  group_by(
    AlphaComparisonGroup,
    Species,
    Ligand
  ) %>%
  
  summarise(
    N_Receptors = n_distinct(Receptor),
    Median_KD_M = median(KD_M),
    .groups = "drop"
  ) %>%
  
  rename(
    Group = AlphaComparisonGroup
  ) %>%
  
  mutate(
    GroupType = "Alpha"
  )


# ------------------------------------------------------------------------------
# 6.2 CALCULATE BETA-GROUP MEDIANS
# ------------------------------------------------------------------------------

beta_medians <- raw_oma %>%
  
  filter(
    !is.na(BetaComparisonGroup)
  ) %>%
  
  group_by(
    BetaComparisonGroup,
    Species,
    Ligand
  ) %>%
  
  summarise(
    N_Receptors = n_distinct(Receptor),
    Median_KD_M = median(KD_M),
    .groups = "drop"
  ) %>%
  
  rename(
    Group = BetaComparisonGroup
  ) %>%
  
  mutate(
    GroupType = "Beta"
  )


# ------------------------------------------------------------------------------
# 6.3 COMBINE AND VALIDATE GROUP-LEVEL MEDIANS
# ------------------------------------------------------------------------------

figure18_medians <- bind_rows(
  alpha_medians,
  beta_medians
) %>%
  
  select(
    GroupType,
    Group,
    Species,
    Ligand,
    N_Receptors,
    Median_KD_M
  )


# Every group/species/ligand combination should have one finite,
# strictly positive median KD value.

if (
  anyNA(figure18_medians$Median_KD_M) ||
  any(!is.finite(figure18_medians$Median_KD_M)) ||
  any(figure18_medians$Median_KD_M <= 0) ||
  
  anyDuplicated(
    figure18_medians[, c(
      "GroupType",
      "Group",
      "Species",
      "Ligand"
