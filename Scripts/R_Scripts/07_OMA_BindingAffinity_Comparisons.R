# ==============================================================================
# 9. CALCULATE SPEARMAN CORRELATIONS FOR FIGURE 18
# ==============================================================================

# Spearman rank correlation quantifies similarity in ligand binding
# preferences between the paired species.
#
# Correlations use the same nine raw KD pairs plotted in each panel.
#
# rho = +1: Identical ligand rankings
# rho =  0: No monotonic rank association
# rho = -1: Reversed ligand rankings
#
# No p-values are calculated, matching the original descriptive analysis.
#
# Applying logarithmic axis scaling does not change Spearman rho because
# the transformation preserves the rank order of positive KD values.

spearman_results <- pair_data %>%
  
  group_by(
    Panel,
    GroupType,
    Group,
    XSpecies,
    YSpecies
  ) %>%
  
  summarise(
    
    N_Ligands = n(),
    
    SpearmanRho = cor(
      KD_X,
      KD_Y,
      method = "spearman",
      use = "everything"
    ),
    
    .groups = "drop"
    
  )


# Confirm that six finite correlations were calculated.

if (
  nrow(spearman_results) != 6L ||
  any(spearman_results$N_Ligands != 9L) ||
  any(!is.finite(spearman_results$SpearmanRho))
) {
  
  stop(
    "Invalid Figure 18 Spearman correlation results."
  )
  
}


# Export the full-precision correlation coefficients.

write_table(
