# ------------------------------------------------------------------------------
# 10.1 CALCULATE SHARED AXIS LIMITS
# ------------------------------------------------------------------------------

# All six scatterplots use the same horizontal and vertical KD ranges.
#
# The limits are derived from all the plotted raw KD medians.
#
# Eight percent padding is added to the logarithmic range to keep
# points from touching the plotting boundaries.

all_log_kd <- log10(
  c(
    pair_data$KD_X,
    pair_data$KD_Y
  )
)

log_min <- min(all_log_kd)

log_max <- max(all_log_kd)

padding <- 0.08 * (
  log_max - log_min
)

axis_limits <- 10^c(
  log_min - padding,
  log_max + padding
)


# ==============================================================================
# 11. GENERATE THE SIX FIGURE 18 SCATTERPLOTS
# ==============================================================================

# Each point represents one ligand's median predicted raw KD in two species.
#
# Both axes are displayed on logarithmic scales.
#
# The dashed y = x diagonal represents equal predicted KD values.
# It is a reference line, not a fitted regression.
#
# Spearman rho is displayed in the subtitle.
#
# The panel titles reproduce the final OSCG terminology.


# ------------------------------------------------------------------------------
# 11.1 DEFINE THE INDIVIDUAL PLOT FUNCTION
# ------------------------------------------------------------------------------

make_kd_plot <- function(panel_letter) {
  
  df <- pair_data %>%
    filter(
      Panel == panel_letter
    )
  
  stat <- spearman_results %>%
    filter(
      Panel == panel_letter
    )
  
  
  if (
    nrow(df) != 9L ||
    nrow(stat) != 1L
  ) {
    
    stop(
      "Missing or duplicated Figure 18 panel: ",
      panel_letter
    )
    
  }
  
  
  # The labels identify which OMA-supported comparison groups
  # contributed to each cross-species comparison.
  #
  # Only the display names are changed; the group definitions and
  # affinity calculations remain unchanged.
  
  group_title <- switch(
    
    panel_letter,
    
    "A" = "OSCG 1 and 3 (α6/α7)",
    
    "B" = "OSCG 4 (αV/α5/α8)",
    
    "C" = "OSCG 5 (β1)",
    
    "D" = "OSCG 5 (β1)",
    
    "E" = "OSCG 5 (β1)",
    
    "F" = "OSCG 6 (β6)"
    
  )
  
  
  ggplot(
    df,
    
    aes(
      x = KD_X,
      y = KD_Y
    )
    
  ) +
    
    # Reference diagonal indicating equal median KD values.
    
    geom_abline(
      slope = 1,
      intercept = 0,
      linetype = "dashed",
      linewidth = 0.7,
      colour = "grey45"
    ) +
    
    # Plot each ligand using its assigned colour.
    
    geom_point(
      aes(colour = Ligand),
      size = 3.3
    ) +
    
    # Add ligand names while reducing text overlap.
    
    ggrepel::geom_text_repel(
      
      aes(
        label = Ligand,
        colour = Ligand
      ),
      
      size = 3.3,
      
      box.padding = 0.35,
      
      point.padding = 0.25,
      
      segment.color = "grey60",
      
      min.segment.length = 0,
      
      max.overlaps = Inf,
      
      seed = 123,
      
      show.legend = FALSE
      
    ) +
    
    # Logarithmically scale the KD axes without modifying data.
    
    scale_x_log10(
      limits = axis_limits,
      labels = scales::label_scientific(digits = 1)
    ) +
    
    scale_y_log10(
      limits = axis_limits,
      labels = scales::label_scientific(digits = 1)
    ) +
    
    scale_colour_manual(
      values = ligand_colours
    ) +
    
    # Add logarithmic axis tick marks.
    
    annotation_logticks(
      sides = "bl",
      
      short = grid::unit(0.08, "cm"),
      
      mid = grid::unit(0.12, "cm"),
      
      long = grid::unit(0.16, "cm")
    ) +
    
    # Preserve equal horizontal and vertical scaling.
    
    coord_fixed() +
    
    labs(
      
      title = group_title,
      
      subtitle = paste0(
        "Spearman \u03c1 = ",
        sprintf("%.3f", stat$SpearmanRho)
      ),
      
      x = paste0(
        "Median predicted KD (M)\n",
        unique(df$XSpecies)
      ),
      
      y = paste0(
        "Median predicted KD (M)\n",
        unique(df$YSpecies)
      )
      
    ) +
    
    theme_bw(
      base_size = 11
    ) +
    
    theme(
      
      legend.position = "none",
      
      panel.grid.minor = element_blank(),
      
      panel.grid.major = element_line(
        colour = "grey90",
        linewidth = 0.35
      ),
      
      plot.title = element_text(
        face = "bold",
        size = 11
      ),
      
      plot.subtitle = element_text(
        size = 10
      ),
      
      axis.title = element_text(
        size = 10
      ),
      
      axis.text = element_text(
        size = 9
      ),
      
      plot.margin = margin(
        8, 12, 8, 8
      )
      
    )
  
}


