# ==============================================================================
# 8. CREATE THE PAIRED KD DATA FOR FIGURE 18
# ==============================================================================

# Every Figure 18 panel contains nine ligand observations.
#
# Each ligand contributes:
#
#   X = Median raw KD for the first species
#   Y = Median raw KD for the second species
#
# Ligands are matched by name so that corresponding measurements
# are compared correctly.


# ------------------------------------------------------------------------------
# 8.1 DEFINE A FUNCTION FOR ONE SPECIES COMPARISON
# ------------------------------------------------------------------------------

make_pair_data <- function(i) {
  
  definition <- comparisons[i, ]
  
  
  # Select medians for the appropriate OSCG-related group.
  
  current <- figure18_medians %>%
    
    filter(
      GroupType == definition$GroupType,
      Group == definition$Group
    )
  
  
  # Extract the two species being compared.
  
  x <- current %>%
    filter(Species == definition$XSpecies)
  
  y <- current %>%
    filter(Species == definition$YSpecies)
  
  
  # Confirm both species have all nine ligands.
  
  if (
    nrow(x) != 9L ||
    nrow(y) != 9L ||
    !setequal(x$Ligand, LIGANDS) ||
    !setequal(y$Ligand, LIGANDS)
  ) {
    
    stop(
      "Figure 18 panel ",
      definition$Panel,
      " does not have nine matched ligands in each species."
    )
    
  }
  
  
  # Arrange the ligand records in the same order.
  
  x <- x[
    match(LIGANDS, x$Ligand),
    ,
    drop = FALSE
  ]
  
  y <- y[
    match(LIGANDS, y$Ligand),
    ,
    drop = FALSE
  ]
  
  
  # Preserve the median KD values and the number of receptor models.
  
  data.frame(
    
    Panel = definition$Panel,
    
    GroupType = definition$GroupType,
    
    Group = definition$Group,
    
    XSpecies = definition$XSpecies,
    
    YSpecies = definition$YSpecies,
    
    Ligand = LIGANDS,
    
    KD_X = x$Median_KD_M,
    
    KD_Y = y$Median_KD_M,
    
    N_Receptors_X = x$N_Receptors,
    
    N_Receptors_Y = y$N_Receptors,
    
    stringsAsFactors = FALSE
    
  )
  
}


