# ------------------------------------------------------------------------------
# 2.1 STANDARDIZE INTEGRIN SEQUENCE IDENTIFIERS
# ------------------------------------------------------------------------------

# FASTA sequence headers contain identifiers such as species abbreviations,
# subunit names, and database accession numbers.
#
# Example original headers:
#
#   NV_a_Alpha5_NvIITGA5
#   SP_a_AlphaP1_XP_030846529
#   HS_b_Beta1_P05556
#
# For clarity in figures and tables, these are shortened to:
#
#   NV_Alpha5
#   SP_AlphaP1
#   HS_Beta1
#
# The abbreviated names preserve two essential pieces of information:
#
#   1. Species identity (HS, SP, NV)
#   2. Integrin subunit identity
#
# The function retains the first and third underscore-separated fields
# from each FASTA header.
#
# IMPORTANT:
# This operation changes sequence labels only.
# It does not modify the amino-acid sequences or numerical distances.

shorten_integrin_names <- function(headers) {
  
  # Divide each sequence header into underscore-separated fields.
  
  pieces <- strsplit(
    headers,
    "_",
    fixed = TRUE
  )
  
  
  # Check that the FASTA headers follow the expected naming convention.
  #
  # This prevents incorrect labels from being silently assigned when
  # an unexpected FASTA header format is encountered.
  
  valid <- lengths(pieces) >= 3L & vapply(
    pieces,
    function(parts) {
      
      parts[1] %in% c("HS", "SP", "NV") &&
        parts[3] != ""
      
    },
    logical(1)
  )
  
  if (!all(valid)) {
    
    stop(
      "Unexpected FASTA header(s): ",
      paste(headers[!valid], collapse = "; "),
      ". Expected species_subunittype_name_identifier format."
    )
    
  }
  
  
  # Construct shortened labels using the species and subunit fields.
  
  shortened <- vapply(
    pieces,
    function(parts) {
      
      paste(
        parts[1],
        parts[3],
        sep = "_"
      )
      
    },
    character(1)
  )
  
  
  # Each sequence must retain a unique identifier.
  #
  # Duplicate labels would make sequence-distance matrices ambiguous.
  
  if (anyDuplicated(shortened)) {
    stop("Duplicate names after shortening FASTA headers.")
  }
  
  return(shortened)
  
}



# ------------------------------------------------------------------------------
# 2.2 IMPORT AND VALIDATE MULTIPLE-SEQUENCE ALIGNMENTS
# ------------------------------------------------------------------------------

# This function imports an existing amino-acid alignment in FASTA format.
#
# ape::read.FASTA(type = "AA") reads the sequences as amino acids.
#
# The alignment is converted to a matrix with:
#
#   Rows    = individual integrin subunit sequences
#   Columns = aligned amino-acid positions
#
# Expected numbers of sequences:
#
#   Alpha: 16
#   Beta:  12
#
# The function also standardizes the sequence identifiers and checks
# that the imported alignment has valid dimensions.

read_alignment <- function(
    file,
    n_expected,
    label
) {
  
  # Import the MUSCLE alignment.
  
  alignment <- ape::read.FASTA(
    file,
    type = "AA"
  )
  
  
  # Convert the alignment to a matrix.
  #
  # This representation is used by the sequence-distance and
  # bootstrap functions.
  
  alignment <- as.matrix(alignment)
  
  
  # Confirm that the alignment contains the expected number
  # of integrin subunit sequences.
  
  if (nrow(alignment) != n_expected) {
    
    stop(
      label,
      ": expected ",
      n_expected,
      " subunits; found ",
      nrow(alignment)
    )
    
  }
  
  
  # Check for missing values and ensure the alignment contains
  # at least two aligned positions.
  
  if (anyNA(alignment) || ncol(alignment) < 2L) {
    
    stop(
      label,
      ": alignment contains NA values or is too short. ",
      "Inspect the FASTA file."
    )
    
  }
  
  
  # Replace long sequence identifiers with standardized labels.
  #
  # This is performed before calculating distances to ensure that
  # exported matrices and figures contain consistent names.
  
  original_names <- rownames(alignment)
  
  rownames(alignment) <- shorten_integrin_names(
    original_names
  )
  
  
  # Report the number of sequences and alignment positions
  # in the R console for verification.
  
  message(
    label,
    " alignment: ",
    nrow(alignment),
    " sequences x ",
    ncol(alignment),
    " sites"
  )
  
  return(alignment)
  
}



# ------------------------------------------------------------------------------
# 2.3 DEFINE THE BOOTSTRAP RECLUSTERING PROCEDURE
# ------------------------------------------------------------------------------

# Bootstrap analysis evaluates how consistently the observed
# sequence-distance clusters are recovered when alignment positions
# are resampled.
#
# During bootstrap analysis, columns of the original alignment are
# sampled with replacement to generate alternative datasets.
#
# Sampling with replacement means that:
#
#   - Some original alignment positions may occur multiple times.
#   - Other positions may be absent from a given replicate.
#   - The total number of alignment columns remains unchanged.
#
# For each resampled alignment, this function:
#
#   1. Recalculates pairwise amino-acid distances.
#   2. Performs complete-linkage hierarchical clustering.
#   3. Converts the resulting clustering into a phylo object.
#
# The phylo representation allows ape::boot.phylo() to determine
# whether the original clusters are recovered.
#
# NOTE:
# Converting the hierarchical clustering to a phylo object does
# not make it an independently inferred phylogenetic tree.

bootstrap_recluster <- function(alignment) {
  
  # Calculate sequence distances for the resampled alignment.
  #
  # The same settings are used for the bootstrap replicates
  # and the original analysis.
  
  d <- ape::dist.aa(
    alignment,
    pairwise.deletion = TRUE,
    scaled = TRUE
  )
  
  
  # Apply complete-linkage hierarchical clustering.
  
  hc <- stats::hclust(
    d,
    method = "complete"
  )
  
  
  # Convert to phylo format for compatibility with boot.phylo().
  
  return(
    ape::as.phylo(hc)
  )
  
}



# ==============================================================================
# 3. DEFINE THE MAIN SEQUENCE-DISTANCE ANALYSIS FUNCTION
# ==============================================================================

# This function performs the complete analysis for one subunit class.
#
# It is called separately for the alpha and beta alignments.
#
# Both analyses use identical statistical methods, while plot dimensions
# may differ to accommodate their different numbers of sequences.
#
# Arguments:
#
# label:
#   Indicates whether alpha or beta subunits are being analyzed.
#
# alignment:
#   Matrix containing the aligned amino-acid sequences.
#
# heatmap_width / heatmap_height:
#   Dimensions of the exported heatmap PDF.
#
# cell_width / cell_height:
#   Dimensions of individual heatmap cells.
#
# tree_width / tree_height:
#   Dimensions of the bootstrap dendrogram PDF.
#
# label_cex:
#   Controls dendrogram label size.

run_one_subunit_type <- function(
    label,
    alignment,
    heatmap_width,
    heatmap_height,
    cell_width,
    cell_height,
    tree_width,
    tree_height,
    label_cex
) {
  
  
  # ============================================================================
  # 3.1 CALCULATE PAIRWISE AMINO-ACID SEQUENCE DISTANCES
  # ============================================================================
  
  # ape::dist.aa() calculates distances between all pairs of sequences
  # in the multiple-sequence alignment.
  #
  # pairwise.deletion = TRUE:
  #
  #   Pairwise deletion is enabled in the ape::dist.aa() function.
  #
  #   Although this option is intended to handle missing information
  #   during pairwise comparisons, the resulting distance matrices
  #   retain contributions from residue-gap differences.
  #
  #   Therefore, the reported distances should not be interpreted
  #   as distances calculated exclusively from ungapped positions.
  #
  # scaled = TRUE:
  #
  #   The calculated sequence differences are scaled relative to
  #   the length of the untrimmed multiple-sequence alignment.
  #
  #   Residue-gap differences contribute to these values, as
  #   confirmed by comparison with the original distance matrices.
  #
  # INTERPRETATION:
  #
  #   Distance = 0.00: No sequence differences in the comparison.
  #   Higher values: Greater sequence dissimilarity.
  #   Lower values: Greater sequence similarity.
  #
  #   These distances describe differences among the aligned
  #   sequences and are not evolutionary divergence estimates
  #   corrected using an amino-acid substitution model.
  
  distance <- ape::dist.aa(
    alignment,
    pairwise.deletion = TRUE,
    scaled = TRUE
  )
  
  
  # Convert the pairwise distances into a square matrix.
  #
  # Both the rows and columns correspond to integrin subunits.
  #
  # Each cell contains the distance between the corresponding
  # pair of amino-acid sequences.
  
  distance_matrix <- as.matrix(distance)
  
  
  # Confirm that the distance matrix contains valid numerical values.
  #
  # Non-finite distances may indicate insufficient comparable
  # alignment positions between certain sequences.
  
  if (any(!is.finite(distance_matrix))) {
    
    stop(
      label,
      ": non-finite distance value detected."
    )
    
  }
  
  
  
  # ============================================================================
  # 3.2 HIERARCHICAL CLUSTERING OF INTEGRIN SUBUNITS
  # ============================================================================
  
  # Hierarchical clustering groups integrin subunits according to
  # their pairwise amino-acid sequence distances.
  #
  # Complete-linkage clustering is used.
  #
  # Under complete linkage, the distance between two clusters is
  # defined as the greatest pairwise distance between their members.
  #
  # Clusters are joined according to this criterion until all
  # sequences are connected in a single hierarchical arrangement.
  #
  # The resulting dendrogram describes patterns of sequence similarity.
  #
  # It does not independently establish evolutionary orthology
  # or infer a phylogenetic history.
  
  clustering <- stats::hclust(
    distance,
    method = "complete"
  )
  
  
  # Convert the hierarchical clustering into a phylo object.
  #
  # This representation is required for bootstrap analysis using
  # ape::boot.phylo() and for plotting annotated branching diagrams.
  
  tree <- ape::as.phylo(
    clustering
  )
  
  
  
  # ============================================================================
  # 3.3 EXPORT NUMERICAL SEQUENCE-DISTANCE MATRIX
  # ============================================================================
  
  # Save the complete pairwise distance matrix as a CSV file.
  #
  # These values provide the numerical basis for the sequence-distance
  # heatmaps reported in Figure 9.
  #
  # Preserving the numerical matrix also allows other researchers
  # to inspect individual sequence comparisons independently
  # of the figure.
  
  utils::write.csv(
    distance_matrix,
    file.path(
      OUTPUT_DIR,
      paste0(
        label,
        "_Pairwise_Sequence_Distances.csv"
      )
    ),
    row.names = TRUE
  )
  
  
  
  # ============================================================================
  # 4. GENERATE SEQUENCE-DISTANCE HEATMAP
  # ============================================================================
  
  # THESIS OUTPUT:
  #
  # Figure 9A: Alpha-subunit sequence-distance heatmap
  # Figure 9B: Beta-subunit sequence-distance heatmap
  #
  # Each heatmap displays pairwise amino-acid distances among all
  # integrin subunits belonging to the corresponding subunit class.
  #
  # Rows and columns are ordered using complete-linkage clustering.
  #
  # The numerical sequence distances are displayed inside the cells
  # to allow direct comparison of individual subunit pairs.
  #
  # The row and column dendrograms are hidden in these heatmaps.
  # Bootstrap-supported clustering trees are presented separately
  # in supplementary figures.
  #
  # IMPORTANT:
  # Although the heatmaps are clustered, the distance values are
  # not transformed or standardized before visualization.
  
  pheatmap::pheatmap(
    distance_matrix,
    
    # Use the previously calculated amino-acid distance object
    # to determine the clustering order.
    
    clustering_distance_rows = distance,
    clustering_distance_cols = distance,
    
    # Apply complete-linkage hierarchical clustering.
    
    clustering_method = "complete",
    
    # Display the sequence distances numerically.
    # Values are rounded to two decimal places for readability.
    
    display_numbers = TRUE,
    number_format = "%.2f",
    
    # Remove borders between individual heatmap cells.
    
    border_color = NA,
    
    # Control the font sizes for row labels, column labels,
    # and numerical cell annotations.
    
    fontsize = 9,
    fontsize_row = 8,
    fontsize_col = 8,
    fontsize_number = 7,
    
    # Rotate column labels to avoid overlap.
    
    angle_col = 90,
    
    # Adjust cell dimensions for each subunit class.
    
    cellwidth = cell_width,
    cellheight = cell_height,
    
    # Hide clustering dendrograms in the heatmap.
    # The clustering still determines the ordering of sequences.
    
    treeheight_row = 0,
    treeheight_col = 0,
    
    # Figure title.
    
    main = paste(
      "Pairwise amino-acid sequence distances among integrin",
      tolower(label),
      "subunits"
    ),
    
    # Save the resulting heatmap as a PDF.
    
    filename = file.path(
      OUTPUT_DIR,
      paste0(
        label,
        "_Sequence_Distance_Heatmap.pdf"
      )
    ),
    
    width = heatmap_width,
    height = heatmap_height
  )
  
  
  
  # ============================================================================
  # 5. BOOTSTRAP SUPPORT ANALYSIS
  # ============================================================================
  
  # PURPOSE:
  #
  # Hierarchical clustering can identify groups of similar sequences,
  # but it does not indicate how sensitive those groupings are
  # to variation in the alignment positions.
  #
  # Bootstrap analysis provides an estimate of cluster stability.
  #
  # This analysis uses 10,000 alignment-column bootstrap replicates.
  #
  # For each replicate:
  #
  #   1. Alignment columns are resampled with replacement.
  #   2. Pairwise sequence distances are recalculated.
  #   3. Complete-linkage clustering is repeated.
  #   4. The resulting clusters are compared with the original tree.
  #
  # A bootstrap support value is the percentage of replicates
  # in which a particular cluster is recovered.
  #
  # For example:
  #
  #   Bootstrap support = 95%
  #
  # means that the cluster was recovered in approximately 95%
  # of the 10,000 bootstrap replicates.
  #
  # Higher percentages indicate greater stability under the chosen
  # resampling procedure.
  #
  # These percentages do not represent probabilities that
  # particular evolutionary relationships are correct.
  
  
  
  # ----------------------------------------------------------------------------
  # 5.1 DEFINE THE SAVED BOOTSTRAP FILE
  # ----------------------------------------------------------------------------
  
  # Bootstrap calculations can be computationally expensive.
  #
  # Therefore, the completed bootstrap results are saved as .rds files.
  #
  # RDS files preserve R objects so that they can be loaded again
  # without recalculating the 10,000 bootstrap replicates.
  
  cache_path <- file.path(
    OUTPUT_DIR,
    paste0(
      label,
      "_Sequence_Clustering_Bootstrap.rds"
    )
  )
  
  
  
  # ----------------------------------------------------------------------------
  # 5.2 RUN OR LOAD THE BOOTSTRAP ANALYSIS
  # ----------------------------------------------------------------------------
  
  if (RUN_BOOTSTRAP) {
    
    # --------------------------------------------------------------------------
    # CALCULATE NEW BOOTSTRAP RESULTS
    # --------------------------------------------------------------------------
    
    # Set the random seed before resampling.
    #
    # The same seed is used for alpha and beta analyses to make
    # their bootstrap runs independently reproducible.
    
    set.seed(SEED)
    
    
    # Run the bootstrap analysis.
    #
    # phy:
    #   Original complete-linkage sequence-distance clustering tree.
    #
    # x:
    #   Original amino-acid alignment matrix.
    #
    # FUN:
    #   Function applied to each bootstrap-resampled alignment.
    #
    # B:
    #   Number of bootstrap replicates.
    #
    # trees = FALSE:
    #   Return bootstrap cluster counts without retaining all
    #   replicate trees.
    #
    # rooted = TRUE:
    #   Use rooted-tree matching conventions for the representation
    #   of the hierarchical clustering.
    #
    #   This does not imply that an evolutionary root was inferred.
    
    counts <- ape::boot.phylo(
      phy = tree,
      x = alignment,
      FUN = bootstrap_recluster,
      B = NBOOT,
      trees = FALSE,
      quiet = FALSE,
      rooted = TRUE
    )
    
    
    # Store the bootstrap counts together with basic information
    # about the analysis settings and alignment.
    #
    # These metadata are later used to check whether a saved
    # bootstrap result is compatible with the current analysis.
    
    cache <- list(
      counts = counts,
      nboot = NBOOT,
      seed = SEED,
      taxon_names = rownames(alignment),
      alignment_columns = ncol(alignment),
      tree = tree
    )
    
    
    # Save the bootstrap object to disk.
    
    saveRDS(
      cache,
      cache_path
    )
    
  } else {
    
    # --------------------------------------------------------------------------
    # REUSE PREVIOUSLY CALCULATED BOOTSTRAP RESULTS
    # --------------------------------------------------------------------------
    
    # Check whether the saved bootstrap object exists.
    #
    # If the bootstrap analysis has never been run, the user
    # must set RUN_BOOTSTRAP <- TRUE.
    
    if (!file.exists(cache_path)) {
      
      stop(
        "No saved bootstrap result for ",
        label,
        ": ",
        cache_path,
        ". Set RUN_BOOTSTRAP <- TRUE for the first run."
      )
      
    }
    
    
    # Load the saved bootstrap object.
    
    cache <- readRDS(
      cache_path
    )
    
    
    # Check compatibility between the cached result and the
    # current analysis.
    #
    # The checks compare:
    #
    #   - Number of bootstrap replicates
    #   - Sequence identifiers and their order
    #   - Number of alignment columns
    #   - Clustering tree structure
    #   - Tree tip labels
    #
    # NOTE:
    # These checks do not compare every amino-acid position.
    # If the alignment contents change, rerun the bootstrap
    # even if the cached file passes these checks.
    
    if (
      !identical(cache$nboot, NBOOT) ||
      !identical(cache$taxon_names, rownames(alignment)) ||
      !identical(cache$alignment_columns, ncol(alignment)) ||
      !identical(cache$tree$edge, tree$edge) ||
      !identical(cache$tree$tip.label, tree$tip.label)
    ) {
      
      stop(
        label,
        ": saved bootstrap object does not match ",
        "the current settings/alignment."
      )
      
    }
    
    
    # Extract previously calculated bootstrap counts.
    
    counts <- cache$counts
    
  }
  
  
  
  # ----------------------------------------------------------------------------
  # 5.3 CONVERT BOOTSTRAP COUNTS TO PERCENTAGES
  # ----------------------------------------------------------------------------
  
  # boot.phylo() returns the number of replicates supporting each cluster.
  #
  # Convert these counts into percentages:
  #
  # Bootstrap support (%) =
  #   (Number of replicates recovering the cluster / NBOOT) x 100
  #
  # Example:
  #
  #   8,500 supporting replicates / 10,000 replicates x 100 = 85%
  #
  # These percentages are displayed on the supplementary dendrograms.
  
  support_percent <- 100 * counts / NBOOT
  
  
  # Create a table containing the bootstrap support values
  # for the internal nodes of the clustering tree.
  #
  # Values are rounded to one decimal place for reporting.
  
  support_table <- data.frame(
    Node = seq_along(support_percent),
    
    BootstrapSupport_Percent = round(
      support_percent,
      1
    )
  )
  
  
  
  # ----------------------------------------------------------------------------
  # 5.4 EXPORT NUMERICAL BOOTSTRAP SUPPORT VALUES
  # ----------------------------------------------------------------------------
  
  # Save the support percentages as a CSV file.
  #
  # The table provides a numerical record of the support values
  # displayed on the supplementary clustering figures.
  
  utils::write.csv(
    support_table,
    file.path(
      OUTPUT_DIR,
      paste0(
        label,
        "_Sequence_Clustering_Bootstrap_Support.csv"
      )
    ),
    row.names = FALSE
  )
  
  
  
  # ============================================================================
  # 6. GENERATE BOOTSTRAP-SUPPORTED CLUSTERING DENDROGRAM
  # ============================================================================
  
  # THESIS OUTPUT:
  #
  # Supplementary Figure: Alpha-subunit sequence-distance clustering
  # Supplementary Figure: Beta-subunit sequence-distance clustering
  #
  # These figures display the complete-linkage clustering structure
  # along with bootstrap support percentages at internal nodes.
  #
  # Branch lengths reflect sequence-distance clustering heights.
  #
  # Node annotations represent the percentage of bootstrap replicates
  # recovering each corresponding cluster.
  #
  # The figures provide information about the stability of
  # sequence-similarity groupings identified in Figure 9.
  #
  # IMPORTANT:
  # The dendrograms are not formal phylogenetic reconstructions.
  
  
  # Define the PDF output filename.
  
  tree_file <- file.path(
    OUTPUT_DIR,
    paste0(
      label,
      "_SequenceDistance_Clustering_Bootstrap.pdf"
    )
  )
  
  
  # Open a PDF graphics device.
  #
  # Subsequent plotting commands will be written to this PDF
  # until the graphics device is closed.
  
  grDevices::pdf(
    tree_file,
    width = tree_width,
    height = tree_height
  )
  
  
  # Save the current graphical settings so they can be restored
  # after the supplementary figure is generated.
  
  old_par <- graphics::par(
    no.readonly = TRUE
  )
  
  
  # tryCatch() ensures graphical settings are restored and the PDF
  # device is closed even if an error occurs while drawing the figure.
  
  tryCatch({
    
    # Adjust plotting margins to provide sufficient space
    # for sequence labels and explanatory annotations.
    
    graphics::par(
      mar = c(4, 2, 5, 12),
      xpd = NA
    )
    
    
    # Plot the hierarchical clustering in a branching format.
    #
    # The phylogram-style representation is used for visualization,
    # even though the underlying tree originates from hierarchical
    # clustering rather than a phylogenetic inference procedure.
    
    graphics::plot(
      tree,
      type = "phylogram",
      cex = label_cex,
      
      main = paste0(
        "Bootstrap-supported sequence-distance clustering\n",
        "of integrin ",
        tolower(label),
        " subunits"
      )
    )
    
    
    # Add bootstrap support percentages to internal nodes.
    #
    # Each label describes how frequently the corresponding cluster
    # was recovered during alignment-column resampling.
    
    ape::nodelabels(
      text = round(support_percent, 1),
      frame = "none",
      cex = 0.7
    )
    
    
    # Add a note identifying the clustering method.
    
    graphics::mtext(
      "Complete-linkage clustering based on pairwise amino-acid sequence distances",
      side = 1,
      line = 2.3,
      cex = 0.8
    )
    
    
    # Add a note describing the bootstrap support values.
    
    graphics::mtext(
      sprintf(
        "Node labels = bootstrap support (%%) from %s alignment-column resamples",
        format(
          NBOOT,
          big.mark = ",",
          scientific = FALSE
        )
      ),
      
      side = 1,
      line = 3.2,
      cex = 0.75
    )
    
  }, finally = {
    
    # Restore previous graphics settings and close the output PDF.
    
    graphics::par(old_par)
    
    grDevices::dev.off()
    
  })
  
  
  # Report successful completion of this subunit analysis.
  
  message(
    "Completed ",
    label,
    "; files saved under ",
    OUTPUT_DIR
  )
  
  
  # Return the distance matrix, clustering tree, and support table.
  #
  # invisible() prevents these large objects from being printed
  # automatically in the R console.
  
  invisible(
    list(
      distance = distance_matrix,
      tree = tree,
      support = support_table
    )
  )
  
}



