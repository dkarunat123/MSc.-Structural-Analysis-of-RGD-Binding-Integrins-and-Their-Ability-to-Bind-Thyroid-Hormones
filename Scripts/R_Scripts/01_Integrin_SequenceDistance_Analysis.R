#
# PROJECT:
# Comparative Structural Analysis of RGD-Binding Integrins and Their Ability
# to Bind Thyroid Hormones
#
# PURPOSE:
# This script examines amino-acid sequence similarity among integrin alpha
# and beta subunits from three species:
#
#   1. Homo sapiens (HS)
#   2. Strongylocentrotus purpuratus (SP)
#   3. Nematostella vectensis (NV)
#
# The analysis evaluates whether integrin subunits cluster according to
# their amino-acid sequence similarities and assesses the stability of
# those clusters through bootstrap resampling.
#
# The results provide sequence-level context for subsequent comparisons
# of integrin structure, predicted thyroid hormone binding affinities,
# and evolutionary relationships.
#
# IMPORTANT:
# Sequence similarity alone does not establish evolutionary orthology.
# Orthology relationships were evaluated separately using the OMA database.
#
# ------------------------------------------------------------------------------
# DATASET
# ------------------------------------------------------------------------------
#
# The dataset contains extracellular amino-acid sequences from:
#
#   - 16 integrin alpha subunits
#   - 12 integrin beta subunits
#
# These sequences were previously aligned using MUSCLE v5.2.
#
# Alpha and beta subunits were aligned separately because they represent
# distinct integrin subunit families.
#
# This script reads the completed multiple-sequence alignments (MSAs).
# It does not perform the MUSCLE alignment itself.
#
# ------------------------------------------------------------------------------
# ANALYSES PERFORMED
# ------------------------------------------------------------------------------
#
# 1. Import and validate the alpha and beta MUSCLE alignments.
#
# 2. Standardize sequence identifiers for figures and output tables.
#
# 3. Calculate pairwise amino-acid sequence distances using ape::dist.aa().
#
# 4. Apply complete-linkage hierarchical clustering to the distance matrices.
#
# 5. Generate sequence-distance heatmaps for alpha and beta subunits.
#
# 6. Estimate clustering support using 10,000 bootstrap replicates
#    generated by resampling alignment columns.
#
# 7. Generate bootstrap-supported sequence-distance clustering dendrograms.
#
# 8. Export distance matrices, bootstrap support values, and figures.
#
# ------------------------------------------------------------------------------
# STATISTICAL METHODS
# ------------------------------------------------------------------------------
#
# Sequence-distance calculation:
#   ape::dist.aa()
#   pairwise.deletion = TRUE
#   scaled = TRUE
#
# Hierarchical clustering:
#   hclust(method = "complete")
#
# Bootstrap support:
#   ape::boot.phylo()
#   10,000 bootstrap replicates
#   Random seed = 123
#
# NOTE:
# The dendrograms represent hierarchical clustering of sequence distances.
# They should not be interpreted as independently inferred phylogenetic trees.
# Bootstrap percentages indicate support for clusters under resampling of
# alignment positions, not probabilities of evolutionary relationships.
#
