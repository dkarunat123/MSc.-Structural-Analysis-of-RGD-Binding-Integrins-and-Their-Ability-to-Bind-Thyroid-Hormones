    entry <- dat[
      (dat$Ligand_1 == a & dat$Ligand_2 == b) |
        (dat$Ligand_1 == b & dat$Ligand_2 == a),
      "Spearman_rho"
    ]
    if (length(entry) != 1L) stop("Missing ligand pair: ", a, "/", b)
    entry
  }
  cat(sprintf("  %-15s TRIAC/TETRAC = %.3f; T3/T4 = %.3f\n",
              sp, lookup_rho("TRIAC", "TETRAC"), lookup_rho("T3", "T4")))
