# ==============================================================================
# 3. VALIDATE THE SAVED LIGAND BOOTSTRAPS FROM SCRIPT 04
# ==============================================================================

# To annotate Figure 14 correctly, we must use the ligand tree AND AU values
# from the SAME pvclust run. The original Figure 14 code recalculated its
# ligand tree separately and then attached AU values by edge number; that can
# mislabel branches if the dendrogram topology or merge order ever changes.
#
# Here we instead read the saved pvclust$hclust and pvclust$edges together.
# The previously exported edge/membership CSV files are cross-checked as an
# additional safeguard against accidental file mixing.
#
# Script 04 stored MD5 checksums of the Script 02 input files in each RDS.
# We check those identifiers before using a saved bootstrap with our data.

SCORES_MD5 <- unname(as.character(tools::md5sum(INPUT_SCORES)))
METADATA_MD5 <- unname(as.character(tools::md5sum(INPUT_METADATA)))

# Recover all ligand names belonging to an internal hclust merge node.
# In hclust$merge, negative values identify leaves; positive values refer to
# earlier merges. This recursion is also used to validate the exported clusters.

members_of_merge <- function(hc, node) {
  if (node < 0L) return(hc$labels[-node])
  c(
    members_of_merge(hc, hc$merge[node, 1]),
    members_of_merge(hc, hc$merge[node, 2])
  )
}

load_verified_bootstrap <- function(species_name, bootstrap_label,
                                    species_matrix) {
  
  stem <- paste0("Step12A_Ligand_pvclust_", bootstrap_label, "_1000000")
  rds_file <- file.path(BOOTSTRAP_DIR, paste0(stem, ".rds"))
  edge_file <- file.path(
    BOOTSTRAP_DIR,
    paste0("Step12A_Ligand_pvclust_Edges_", bootstrap_label,
           "_1000000.csv")
  )
  cluster_file <- file.path(
    BOOTSTRAP_DIR,
    paste0("Step12A_Ligand_pvclust_Clusters_", bootstrap_label,
           "_1000000.csv")
  )
  
  for (path in c(rds_file, edge_file, cluster_file)) {
    if (!file.exists(path)) {
      stop("Missing bootstrap file: ", path, "\nRun Script 04 first.")
    }
  }
  
  pv <- readRDS(rds_file)
  if (!inherits(pv, "pvclust") || is.null(pv$hclust) ||
      is.null(pv$edges)) {
    stop("Unexpected RDS bootstrap object for ", species_name)
  }
  
  # Verify the saved analysis was calculated from these actual source files,
  # ligands and receptor IDs, using the correct statistical settings.
  cache <- attr(pv, "integrin_cache_details")
  if (is.null(cache) ||
      !identical(cache$score_file_md5, SCORES_MD5) ||
      !identical(cache$metadata_file_md5, METADATA_MD5) ||
      !identical(cache$species, species_name) ||
      !identical(cache$receptor_ids, rownames(species_matrix)) ||
      !identical(cache$ligand_ids, colnames(species_matrix)) ||
      !identical(cache$nboot, 1000000L) ||
      !identical(cache$method_dist, "euclidean") ||
      !identical(cache$method_hclust, "complete")) {
    stop(
      "Bootstrap provenance does not match Script 02 data for ",
      species_name, ". Re-run Script 04 on the current prepared inputs."
    )
  }
  
  hc <- pv$hclust
  edges <- as.data.frame(pv$edges)
  n_internal <- length(LIGANDS) - 1L
  
  if (!setequal(hc$labels, LIGANDS) || nrow(edges) != n_internal ||
      !all(c("au", "bp") %in% names(edges)) ||
      any(!is.finite(edges$au)) || any(!is.finite(edges$bp))) {
    stop("Incomplete or invalid pvclust edges for ", species_name)
  }
  
  # The original analysis and Script 04 both used complete-linkage Euclidean
  # clustering. Independently reconstruct it to confirm that every ligand
  # merge belongs to the same cluster, regardless of drawing orientation.
  independent_hc <- stats::hclust(
    stats::dist(t(species_matrix), method = "euclidean"),
    method = "complete"
  )
  original_clusters <- lapply(seq_len(n_internal), function(i) {
    sort(members_of_merge(hc, i))
  })
  independent_clusters <- lapply(seq_len(n_internal), function(i) {
    sort(members_of_merge(independent_hc, i))
  })
  encode_cluster <- function(x) paste(sort(x), collapse = "|")
  if (!setequal(vapply(original_clusters, encode_cluster, character(1)),
                vapply(independent_clusters, encode_cluster, character(1)))) {
    stop("Saved ligand topology differs from current data: ", species_name)
  }
  
  # Confirm that each exported AU/BP value matches the corresponding node
  # in the RDS object. The CSV 'edge' column is the pvclust merge number.
  exported_edges <- utils::read.csv(edge_file, check.names = FALSE)
  if (nrow(exported_edges) != n_internal ||
      !all(c("edge", "au", "bp") %in% names(exported_edges)) ||
      !identical(as.integer(exported_edges$edge), seq_len(n_internal)) ||
      !isTRUE(all.equal(exported_edges$au, edges$au,
                        tolerance = 1e-12)) ||
      !isTRUE(all.equal(exported_edges$bp, edges$bp,
                        tolerance = 1e-12))) {
    stop("Bootstrap edge CSV differs from saved RDS for ", species_name)
  }
  
  # Confirm every cluster's constituent ligands and displayed AU percentage.
  exported_clusters <- utils::read.csv(cluster_file, check.names = FALSE)
  if (nrow(exported_clusters) != n_internal ||
      !all(c("Edge", "Ligands", "AU_Percent", "BP_Percent") %in%
           names(exported_clusters)) ||
      !identical(as.integer(exported_clusters$Edge), seq_len(n_internal)) ||
      !isTRUE(all.equal(exported_clusters$AU_Percent, 100 * edges$au,
                        tolerance = 1e-10)) ||
      !isTRUE(all.equal(exported_clusters$BP_Percent, 100 * edges$bp,
                        tolerance = 1e-10))) {
    stop("Bootstrap cluster CSV differs from saved RDS for ", species_name)
  }
  for (i in seq_len(n_internal)) {
    csv_members <- trimws(strsplit(exported_clusters$Ligands[i], ";",
                                   fixed = TRUE)[[1]])
    if (!setequal(csv_members, original_clusters[[i]])) {
      stop("Incorrect ligand membership in ", species_name,
           " bootstrap edge ", i)
    }
  }
  
  message("Validated saved pvclust tree and AU data: ", species_name)
  pv
}


# ==============================================================================
# 4. BUILD DENDROGRAM COORDINATES FOR FIGURE 14
# ==============================================================================

# ggplot2 needs explicit coordinates to place the ligand dendrogram directly
# above the heatmap and write red AU labels on the correct merges.
#
# The structure matches the final Figure 14 plotting code originally used:
#   - Leaf x-positions are assigned in hclust$order.
#   - Internal nodes are located midway between their two children.
#   - Horizontal and vertical line segments represent dendrogram branches.
#   - Each node gets AU (%) from the matching pvclust edge.
#
# The root node (joining all nine ligands) is still drawn but its support
# value is not labelled because that cluster necessarily contains everything.

make_dendrogram_data <- function(hc, edges) {
  n <- length(hc$labels)
  if (n != length(LIGANDS) || nrow(edges) != (n - 1L)) {
    stop("Dendrogram and bootstrap edges have incompatible dimensions.")
  }
  
  leaf_x <- numeric(n)
  leaf_x[hc$order] <- seq_len(n)
  node_x <- numeric(n - 1L)
  segments <- vector("list", 3L * (n - 1L))
  nodes <- vector("list", n - 1L)
  k <- 1L
  
  for (i in seq_len(n - 1L)) {
    left <- hc$merge[i, 1]
    right <- hc$merge[i, 2]
    
    left_x <- if (left < 0L) leaf_x[-left] else node_x[left]
    right_x <- if (right < 0L) leaf_x[-right] else node_x[right]
    left_y <- if (left < 0L) 0 else hc$height[left]
    right_y <- if (right < 0L) 0 else hc$height[right]
    
    parent_x <- (left_x + right_x) / 2
    parent_y <- hc$height[i]
    node_x[i] <- parent_x
    
    segments[[k]] <- data.frame(
      x = left_x, xend = left_x, y = left_y, yend = parent_y
    )
    segments[[k + 1L]] <- data.frame(
      x = left_x, xend = right_x, y = parent_y, yend = parent_y
    )
    segments[[k + 2L]] <- data.frame(
      x = right_x, xend = right_x, y = right_y, yend = parent_y
    )
    k <- k + 3L
    
    nodes[[i]] <- data.frame(
      Edge = i,
      X = parent_x,
      Height = parent_y,
      AU_Percent = 100 * edges$au[i],
      BP_Percent = 100 * edges$bp[i],
      Ligands = paste(sort(members_of_merge(hc, i)), collapse = "; "),
      stringsAsFactors = FALSE
    )
  }
  
  list(
    segments = do.call(rbind, segments),
    nodes = do.call(rbind, nodes),
    ligand_order = hc$labels[hc$order]
  )
}


# ==============================================================================
# 5. GENERATE FIGURE 14: SPECIES-SPECIFIC ABSOLUTE-AFFINITY HEATMAPS
# ==============================================================================

# The receptor models are hierarchically clustered for ROW ORDER only.
# Their dendrogram is hidden, matching the final thesis Figure 14.
#
# Ligands are ordered using the saved pvclust dendrogram from Script 04.
# Their tree is displayed above the heatmap, with AU support in red.
#
# The palette's numerical minimum and maximum are set independently from
# each species-specific 8/24/16 x 9 matrix. No Z-score or other rescaling is
# performed on the underlying -log10(KD) affinities.

make_figure14 <- function(species_name, figure_label, species_matrix, pv) {
  
  receptor_hc <- stats::hclust(
    stats::dist(species_matrix, method = "euclidean"),
    method = "complete"
  )
  
  receptor_order <- rownames(species_matrix)[receptor_hc$order]
  dendro <- make_dendrogram_data(pv$hclust, as.data.frame(pv$edges))
  ligand_order <- dendro$ligand_order
  
  ordered_matrix <- species_matrix[
    receptor_order, ligand_order, drop = FALSE
  ]
  
  # Save the exact matrix and display order used in this figure. These
  # numerical values are unchanged by the plotting procedure.
  write_table(
    data.frame(Receptor = rownames(ordered_matrix), ordered_matrix,
               check.names = FALSE, row.names = NULL),
    paste0("Figure14_", figure_label, "_OrderedAffinityMatrix.csv")
  )
  write_table(
    dendro$nodes,
    paste0("Figure14_", figure_label, "_LigandClusters_AU.csv")
  )
  
  # Convert to a long table with explicit numerical tile coordinates.
  heat_df <- as.data.frame(as.table(ordered_matrix))
  names(heat_df) <- c("Receptor", "Ligand", "Affinity")
  heat_df$Ligand_x <- match(heat_df$Ligand, ligand_order)
  heat_df$Receptor_y <- match(heat_df$Receptor, receptor_order)
  
  # Exclude the root edge only from the LABELS, not the dendrogram lines.
  nodes_to_label <- dendro$nodes[
    dendro$nodes$Edge != nrow(dendro$nodes), , drop = FALSE
  ]
  
  # ---------------------------------------------------------------------------
  # 5.1 TOP PANEL: LIGAND DENDROGRAM AND AU BOOTSTRAP SUPPORT
  # ---------------------------------------------------------------------------
  
  p_dend <- ggplot() +
    geom_segment(
      data = dendro$segments,
      aes(x = x, xend = xend, y = y, yend = yend),
      linewidth = 0.45
    ) +
    geom_text(
      data = nodes_to_label,
      aes(x = X, y = Height, label = round(AU_Percent)),
      colour = "red3", size = 3.2, vjust = -0.45
    ) +
    scale_x_continuous(
      limits = c(0.5, ncol(species_matrix) + 0.5),
      expand = c(0, 0)
    ) +
    scale_y_continuous(expand = expansion(mult = c(0.02, 0.18))) +
    coord_cartesian(clip = "off") +
    labs(title = paste0(species_name,
                        ": hierarchical clustering of binding-affinity profiles")) +
    theme_void() +
    theme(
      plot.title = element_text(face = "bold", size = 14, hjust = 0.5),
      plot.margin = margin(t = 8, r = 8, b = 0, l = 8)
    )
  
  # ---------------------------------------------------------------------------
  # 5.2 BOTTOM PANEL: AFFINITY HEATMAP
  # ---------------------------------------------------------------------------
  
  p_heat <- ggplot(heat_df, aes(
    x = Ligand_x, y = Receptor_y, fill = Affinity
  )) +
    geom_tile() +
    scale_x_continuous(
      breaks = seq_along(ligand_order), labels = ligand_order,
      limits = c(0.5, length(ligand_order) + 0.5), expand = c(0, 0)
    ) +
    scale_y_reverse(
      breaks = seq_along(receptor_order), labels = receptor_order,
      limits = c(length(receptor_order) + 0.5, 0.5),
      position = "right", expand = c(0, 0)
    ) +
    scale_fill_gradientn(
      colours = AFFINITY_COLOURS,
      limits = range(species_matrix),
      name = expression(-log[10](K[D]))
    ) +
    labs(x = NULL, y = NULL) +
    theme_minimal(base_size = 10) +
    theme(
      panel.grid = element_blank(),
      axis.text.x = element_text(angle = 45, hjust = 1, vjust = 1, size = 10),
      axis.text.y = element_text(size = 9),
      axis.ticks = element_blank(),
      legend.title = element_text(size = 10),
      legend.text = element_text(size = 9),
      plot.margin = margin(t = 0, r = 8, b = 8, l = 8)
    )
  
  # ---------------------------------------------------------------------------
  # 5.3 ASSEMBLE AND EXPORT THE PDF
  # ---------------------------------------------------------------------------
  
  heatmap_height <- max(4, nrow(species_matrix) * 0.30)
  final_plot <- (p_dend / p_heat) +
    patchwork::plot_layout(heights = c(1.5, heatmap_height))
  
  output_height <- max(7, 4.5 + nrow(species_matrix) * 0.25)
  output_file <- file.path(
    OUTPUT_DIR,
    paste0("Figure14_", figure_label, "_AbsoluteAffinity_AU.pdf")
  )
  
  ggplot2::ggsave(
    filename = output_file, plot = final_plot,
    width = 11, height = output_height, units = "in"
  )
  
  message("Saved Figure 14 panel: ", output_file)
  invisible(list(
    receptor_order = receptor_order,
    ligand_order = ligand_order,
    affinity_range = range(species_matrix)
  ))
}


# ==============================================================================
# 6. GENERATE FIGURE 15: LIGAND-TO-LIGAND SPEARMAN HEATMAPS
# ==============================================================================

# Each ligand is represented by its predicted affinity across all receptor
# models WITHIN that species. For example, the human TRIAC vector has eight
# entries (one per human heterodimer), and its correlation with TETRAC asks
# whether the two compounds tend to RANK human heterodimers similarly.
#
# cor(species_matrix) compares COLUMNS = ligands. Do not transpose it.
# The resulting 9 x 9 matrix is clustered using distance (1 - rho).
#
# Unlike Figure 14, Figure 15 uses the SAME -1 to +1 colour scale for each
# species. Numerical Spearman rho values appear inside each heatmap cell.

make_figure15 <- function(species_name, figure_label, species_matrix) {
  
  ligand_cor <- stats::cor(
    species_matrix,
    method = "spearman",
    use = "pairwise.complete.obs"
  )
  
  if (!identical(dim(ligand_cor), c(9L, 9L)) ||
      any(!is.finite(ligand_cor))) {
    stop("Invalid 9 x 9 ligand correlations for ", species_name)
  }
  
  # A positive rho indicates that both ligands tend to rank receptor models
  # similarly. Correlation distance ranges from 0 (rho=1) to 2 (rho=-1).
  correlation_hc <- stats::hclust(
    stats::as.dist(1 - ligand_cor), method = "complete"
  )
  
  pdf_file <- file.path(
    OUTPUT_DIR,
    paste0("Figure15_", figure_label, "_Ligand_Spearman.pdf")
  )
  
  pheatmap::pheatmap(
    ligand_cor,
    cluster_rows = correlation_hc,
    cluster_cols = correlation_hc,
    color = CORRELATION_COLOURS,
    breaks = seq(-1, 1, length.out = 101),
    border_color = NA,
    display_numbers = TRUE,
    number_format = "%.2f",
