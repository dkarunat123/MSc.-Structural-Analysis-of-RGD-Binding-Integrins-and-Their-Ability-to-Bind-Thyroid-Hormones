# 8. EXECUTE BOTH FIGURES AND STATISTICS FOR ALL THREE SPECIES
# ==============================================================================

# Create species-specific subsets from the metadata, preserving original
# receptor order and maintaining the distinction between three study species.
# The saved bootstrap object supplies both the precise ligand dendrogram and
# AU annotations for Figure 14. Figure 15 correlations are calculated anew
# from the same prepared affinity scores.

all_descriptive <- vector("list", nrow(SPECIES))
all_pairwise <- vector("list", nrow(SPECIES))
all_run_summaries <- vector("list", nrow(SPECIES))

for (i in seq_len(nrow(SPECIES))) {
  
  species_name <- SPECIES$Name[i]
  figure_label <- SPECIES$Label[i]
  bootstrap_label <- SPECIES$BootstrapLabel[i]
  
  message("\n===============================================")
  message("Processing ", species_name, " (Figure 14 and Figure 15)")
  message("===============================================")
  
  receptor_ids <- metadata$Receptor[metadata$Species == species_name]
  species_matrix <- AFFINITY[receptor_ids, LIGANDS, drop = FALSE]
  
  if (nrow(species_matrix) != SPECIES$N_Receptors[i] ||
      ncol(species_matrix) != length(LIGANDS)) {
    stop("Species matrix dimensions are incorrect for ", species_name)
  }
  
  # Validate the original Script 04 bootstrap instead of recomputing it.
  pv <- load_verified_bootstrap(
    species_name, bootstrap_label, species_matrix
  )
  
  figure14_info <- make_figure14(
    species_name, figure_label, species_matrix, pv
  )
  
  ligand_cor <- make_figure15(
    species_name, figure_label, species_matrix
  )
  
  all_descriptive[[i]] <- summarize_species_ligands(
    species_name, species_matrix
  )
  
  # Save each unique ligand-pair Spearman rho as a long table, so external
  # reviewers do not have to manually inspect a matrix to find comparisons.
  # A 9 x 9 matrix has 36 distinct pairs, excluding nine diagonal entries.
  pair_index <- which(upper.tri(ligand_cor), arr.ind = TRUE)
  all_pairwise[[i]] <- data.frame(
    Species = species_name,
    Ligand_1 = rownames(ligand_cor)[pair_index[, 1]],
    Ligand_2 = colnames(ligand_cor)[pair_index[, 2]],
    Spearman_rho = ligand_cor[pair_index],
    stringsAsFactors = FALSE
  )
  
  all_run_summaries[[i]] <- data.frame(
    Species = species_name,
    N_Receptors = nrow(species_matrix),
    N_Ligands = ncol(species_matrix),
    Min_NegLog10KD = figure14_info$affinity_range[1],
    Max_NegLog10KD = figure14_info$affinity_range[2],
    Figure14_Ligand_Clustering = "Euclidean/complete (Script 04)",
    Figure15_Ligand_Clustering = "1-Spearman/complete",
    Bootstrap_Replicates_Per_Scale = 1000000L,
    stringsAsFactors = FALSE
  )
}


