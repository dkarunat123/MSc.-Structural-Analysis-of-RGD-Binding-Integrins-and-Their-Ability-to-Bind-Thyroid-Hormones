}


# ==============================================================================
# 7. CALCULATE SPECIES-SPECIFIC DESCRIPTIVE STATISTICS
# ==============================================================================

# Report the distribution of each ligand's predicted affinities across its
# species-specific receptor repertoire. These values underlie the statements
# about median ligand preferences in thesis Section 3.5.
#
# These modelled heterodimers are NOT independent biological replicates.
# Accordingly, this section is descriptive: no species-level ANOVA or
# Kruskal-Wallis test is performed.

summarize_species_ligands <- function(species_name, species_matrix) {
  do.call(rbind, lapply(LIGANDS, function(ligand) {
    x <- species_matrix[, ligand]
    qs <- as.numeric(stats::quantile(x, probs = c(0.25, 0.75)))
    
    data.frame(
      Species = species_name,
      Ligand = ligand,
      N_Receptors = length(x),
      Mean = mean(x),
      SD = stats::sd(x),
      Median = stats::median(x),
      Q1 = qs[1],
      Q3 = qs[2],
      IQR = stats::IQR(x),
      Min = min(x),
      Max = max(x),
      stringsAsFactors = FALSE
    )
  }))
}


