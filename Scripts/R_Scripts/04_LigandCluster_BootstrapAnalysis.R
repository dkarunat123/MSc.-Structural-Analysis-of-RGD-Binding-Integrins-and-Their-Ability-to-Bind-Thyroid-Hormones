
# ==============================================================================
# SCRIPT 04: SPECIES-SPECIFIC LIGAND CLUSTER BOOTSTRAP ANALYSIS
# ==============================================================================
#
# PROJECT:
# Comparative Structural Analysis of RGD-Binding Integrins and Their Ability
# to Bind Thyroid Hormones
#
# PURPOSE:
# Assess the stability of ligand-affinity clusters separately in Homo sapiens,
# Strongylocentrotus purpuratus, and Nematostella vectensis using multiscale
# bootstrap resampling implemented in the R package pvclust.
#
# BIOLOGICAL QUESTION:
# Within each species, which ligands exhibit similar patterns of predicted
# absolute binding affinity across the modeled integrin heterodimers, and how
# consistently are these ligand clusters recovered under resampling?
#
# INPUTS (created by Script 02):
#   Results/02_Prepare_Integrin_BindingData_RESULTS/
#     BindingAffinity_NegLog10KD_Wide.csv
#     Receptor_Metadata_OMA.csv
#
# STUDY DESIGN:
#   H. sapiens       :  8 modeled integrin heterodimers x 9 ligands
#   S. purpuratus    : 24 modeled integrin heterodimers x 9 ligands
#   N. vectensis     : 16 modeled integrin heterodimers x 9 ligands
#
# ANALYSIS SETTINGS (retained from original Script2C.R):
#   Analysis objects: nine ligands (COLUMNS of the species-specific matrix)
#   Observations:     integrin heterodimers (ROWS of that matrix)
#   Distance:         Euclidean, using unstandardized -log10(KD) values
#   Clustering:       complete-linkage hierarchical clustering
#   Bootstrap:        pvclust multiscale bootstrap, 1,000,000 replicates
#   Random seed:      123, reset independently for each species
#   Parallel:         FALSE
#   Resampling scales: pvclust defaults, r = seq(0.5, 1.4, by = 0.1)
#
# IMPORTANT STATISTICAL NOTES:
#   - The rows (heterodimers) are resampled; the ligand columns are clustered.
#   - DO NOT transpose the data before calling pvclust().
#   - AU (approximately unbiased) and BP (bootstrap probability) are distinct
#     quantities; AU is used to annotate the ligand dendrogram in Figure 14.
#   - AU values summarize cluster support under pvclust's multiscale procedure.
#     They are not probabilities that a biological binding mechanism is true.
#   - These are COMPUTATIONALLY PREDICTED binding-affinity values. The analysis
#     does not experimentally establish ligand binding or receptor function.
#   - No row-wise or column-wise standardization is performed: Euclidean
#     distances reflect differences in the supplied absolute affinity scores.
#   - Heterodimer models are observations, not independent biological samples.
#
# THESIS REFERENCES:
#   Methods: Section 2.8.3 (Spearman Correlation and Bootstrap Analyses)
#   Results: Section 3.6.3 (Bootstrap support for ligand clusters)
#   Figure 14: species-specific affinity heatmaps with ligand AU labels
#
# OUTPUT DIRECTORY:
#   Results/04_LigandCluster_BootstrapAnalysis_RESULTS/
#
# REPRODUCIBILITY:
#   The original data are not modified. Completed pvclust objects are stored
#   as RDS files and can be reloaded to regenerate edge tables and plots.
#   An input fingerprint is stored with each result to prevent inadvertently
#   reusing bootstrap output calculated from different input files.
#
# RUNNING THIS SCRIPT:
#   Manually set the working directory to R_Scripts. Run Script 02 first.
#   Script 04 automatically creates its output directory. No setwd() is used.
# ==============================================================================


# ==============================================================================
# 0. SETTINGS, PATHS, AND DEPENDENCIES
# ==============================================================================

# Both input files are generated by Script 02 and read in place. No manual
# copying of prepared CSV files into Data/ is necessary.

INPUT_DIR <- file.path(
  "Results",
  "02_Prepare_Integrin_BindingData_RESULTS"
)

INPUT_SCORES <- file.path(INPUT_DIR, "BindingAffinity_NegLog10KD_Wide.csv")
INPUT_METADATA <- file.path(INPUT_DIR, "Receptor_Metadata_OMA.csv")

# Keep all outputs for this analysis in its own numbered results directory.

OUTPUT_DIR <- file.path(
  "Results",
  "04_LigandCluster_BootstrapAnalysis_RESULTS"
)

dir.create(OUTPUT_DIR, recursive = TRUE, showWarnings = FALSE)

# Match the computational settings used in the original million-replicate run.
# pvclust performs multiscale resampling at multiple effective sample sizes.
# One million is the specified number of replicates at each scale.

NBOOT <- 1000000L
SEED <- 123L
RESAMPLING_SCALES <- seq(0.5, 1.4, by = 0.1)

# Saved results are automatically reused when their recorded input checksums
# and analysis settings match. Set TRUE only if you intentionally want to
# recompute every species (for example, to confirm the results independently).
# A fresh run with 1,000,000 bootstraps per scale can be computationally costly.

FORCE_RERUN <- FALSE

# Separate thresholds are retained from the original plots:
#   AU >= 95%: standard pvclust diagnostic dendrogram
#   AU >= 90%: clean, AU-only dendrogram used for reporting

DIAGNOSTIC_AU_THRESHOLD <- 0.95
REPORTING_AU_THRESHOLD <- 0.90

# pvclust is the only external R package required by this script.
if (!requireNamespace("pvclust", quietly = TRUE)) {
  stop(
    "Package 'pvclust' is required. Install it with ",
    "install.packages('pvclust')."
  )
}

for (path in c(INPUT_SCORES, INPUT_METADATA)) {
  if (!file.exists(path)) {
    stop("Missing input: ", path, "\nRun Script 02 first.")
  }
}


# ==============================================================================
# 1. IMPORT AND VALIDATE THE PREPARED AFFINITY DATA
# ==============================================================================

# The wide score table has one receptor per row and one ligand per column:
#   Receptor | Cilengitide | T3 | T4 | TRIAC | ... | T4AM
#
# Scores are ALREADY -log10(KD), as checked against raw KD in Script 02.
# Applying -log10() again would produce scientifically incorrect results.

scores <- utils::read.csv(
  INPUT_SCORES,
  stringsAsFactors = FALSE,
  check.names = FALSE
)

metadata <- utils::read.csv(
  INPUT_METADATA,
  stringsAsFactors = FALSE,
  check.names = FALSE
)

LIGANDS <- c(
  "Cilengitide", "T3", "T4", "TRIAC", "TETRAC",
  "sT3", "sT4", "rT3", "T4AM"
)

SPECIES <- data.frame(
  Name = c("H. sapiens", "S. purpuratus", "N. vectensis"),
  FileLabel = c("H_sapiens", "S_purpuratus", "N_vectensis"),
  ExpectedReceptors = c(8L, 24L, 16L),
  stringsAsFactors = FALSE
)

# Validate columns, receptor counts, and identifiers before computing anything.
if (!"Receptor" %in% names(scores)) {
  stop("Affinity data must include the 'Receptor' column.")
}
if (!all(c("Receptor", "Species") %in% names(metadata))) {
  stop("Receptor metadata must include 'Receptor' and 'Species'.")
}
if (!identical(names(scores)[-1], LIGANDS)) {
  stop("Unexpected ligand names/order in the Script 02 affinity matrix.")
}
if (nrow(scores) != 48L || nrow(metadata) != 48L) {
  stop("Expected 48 receptors in both prepared input tables.")
}
if (anyNA(scores$Receptor) || anyNA(metadata$Receptor) ||
    anyDuplicated(scores$Receptor) || anyDuplicated(metadata$Receptor) ||
    any(!nzchar(scores$Receptor)) || any(!nzchar(metadata$Receptor))) {
  stop("Missing, empty, or duplicate receptor identifiers found.")
}
if (!setequal(scores$Receptor, metadata$Receptor)) {
  stop("Receptor identifiers disagree between the two Script 02 outputs.")
}

# Align metadata to the score matrix by receptor ID, not by row position.
# This prevents species assignments from being silently misapplied if one
# prepared CSV has been reordered by a spreadsheet program or collaborator.

metadata <- metadata[match(scores$Receptor, metadata$Receptor), , drop = FALSE]

if (anyNA(metadata$Species) ||
    !setequal(unique(metadata$Species), SPECIES$Name)) {
  stop("Unexpected or missing species assignment in receptor metadata.")
}

observed_counts <- as.integer(table(factor(
  metadata$Species,
  levels = SPECIES$Name
)))

if (!identical(observed_counts, SPECIES$ExpectedReceptors)) {
  stop("Species receptor counts do not match the expected 8 / 24 / 16.")
}

# Validate all affinity columns before converting them into a numeric matrix.
if (!all(vapply(scores[, LIGANDS, drop = FALSE], is.numeric, logical(1)))) {
  stop("All ligand affinity columns must be numeric.")
}

score_matrix <- as.matrix(scores[, LIGANDS, drop = FALSE])
rownames(score_matrix) <- scores$Receptor
storage.mode(score_matrix) <- "double"

if (any(!is.finite(score_matrix))) {
  stop("Missing, infinite, or nonnumeric binding-affinity score detected.")
}

message(
  "Validated input: ", nrow(score_matrix), " receptors x ",
  ncol(score_matrix), " ligands (", length(score_matrix), " scores)."
)


# ==============================================================================
# 2. RECORD INPUT PROVENANCE FOR REPRODUCIBLE BOOTSTRAP CACHING
# ==============================================================================

# pvclust is computationally intensive at NBOOT = 1,000,000. To avoid
# accidentally repeating a finished analysis, each saved RDS object records:
#   - MD5 fingerprints of both input files
#   - species/receptor identities
#   - ligand identities and their order
#   - the bootstrap seed and statistical settings
#
# If anything in that record changes, the affected result is recomputed.
# Changing only plotting settings does not require recomputing bootstrap values.
#
# IMPORTANT: Older RDS files created by the original Script2C.R do not carry
# these provenance attributes, so they cannot be automatically verified and
# will be recomputed by this version.

SCORE_CHECKSUM <- unname(as.character(tools::md5sum(INPUT_SCORES)))
METADATA_CHECKSUM <- unname(as.character(tools::md5sum(INPUT_METADATA)))

make_cache_details <- function(species_name, species_matrix) {
  list(
    species = species_name,
    receptor_ids = rownames(species_matrix),
    ligand_ids = colnames(species_matrix),
    score_file_md5 = SCORE_CHECKSUM,
    metadata_file_md5 = METADATA_CHECKSUM,
    nboot = NBOOT,
    seed = SEED,
    method_dist = "euclidean",
    method_hclust = "complete",
    scales = RESAMPLING_SCALES,
    parallel = FALSE
  )
}


# ==============================================================================
# 3. FUNCTION TO EXTRACT LIGAND MEMBERSHIP FOR EACH CLUSTER
# ==============================================================================

# An hclust object has one merge row per internal cluster (nine ligands give
# eight internal nodes). Negative merge indices refer to original ligand
# leaves; positive indices refer to previously formed internal clusters.
#
# Using the dendrogram saved INSIDE the pvclust result ensures that the AU
# values are linked to the correct nodes. This is important for Script 05,
# where AU percentages will be placed on the Figure 14 ligand dendrogram.

make_cluster_membership <- function(pv_result) {
  
  hc <- pv_result$hclust
  merge <- hc$merge
  edge_values <- as.data.frame(pv_result$edges)
  
  if (nrow(edge_values) != nrow(merge)) {
    stop("Bootstrap edge count does not match the ligand dendrogram.")
  }
  
  get_ligands <- function(node) {
    if (node < 0L) {
      return(hc$labels[-node])
    }
    c(get_ligands(merge[node, 1]), get_ligands(merge[node, 2]))
  }
  
  member_list <- lapply(seq_len(nrow(merge)), get_ligands)
  
  data.frame(
    Edge = seq_len(nrow(merge)),
    N_Ligands = lengths(member_list),
    Ligands = vapply(
      member_list,
      function(x) paste(sort(x), collapse = "; "),
      character(1)
    ),
    AU_Percent = 100 * edge_values$au,
    BP_Percent = 100 * edge_values$bp,
    stringsAsFactors = FALSE
  )
}


# ==============================================================================
# 4. FUNCTION TO EXPORT A BOOTSTRAP-SUPPORTED LIGAND DENDROGRAM
# ==============================================================================

# Two complementary figures are generated from the SAME saved bootstrap
# result, without recalculating any bootstrap samples:
#
#   DIAGNOSTIC: AU/BP labels, edge numbers, and AU >= 95% rectangles.
#   CLEAN:      AU labels only, no BP or edge numbers, AU >= 90% rectangles.
#
# pvrect() uses the selected AU threshold to outline supported clusters.
# These rectangles are a graphical aid and are not additional statistical
# tests or a transformation of the bootstrap results.

save_bootstrap_plot <- function(pv_result, species_name, output_path,
                                au_threshold, au_only = FALSE) {
  
  grDevices::pdf(output_path, width = 11, height = 9)
  on.exit(grDevices::dev.off(), add = TRUE)
  
  graphics::par(mar = c(8, 6, 6, 4) + 0.1, xpd = NA)
  
  if (au_only) {
    plot(
      pv_result,
      print.pv = "au",
      print.num = FALSE,
      main = paste0(
        "Ligand clustering in ", species_name,
        "\n1,000,000 multiscale bootstrap replicates"
      ),
      cex = 0.9
    )
  } else {
    plot(
      pv_result,
      main = paste0(
        "Ligand clustering in ", species_name,
        "\n1,000,000 multiscale bootstrap replicates"
      ),
      cex = 0.9
    )
  }
  
  pvclust::pvrect(pv_result, alpha = au_threshold, pv = "au")
  invisible(output_path)
}


# ==============================================================================
# 5. PER-SPECIES MULTISCALE BOOTSTRAP ANALYSIS
# ==============================================================================

run_species_bootstrap <- function(species_name, file_label,
                                  expected_receptors) {
  
  # ---------------------------------------------------------------------------
  # 5.1 EXTRACT THE SPECIES-SPECIFIC RECEPTOR x LIGAND MATRIX
  # ---------------------------------------------------------------------------
  # Keep the same receptor order as the original wide affinity table.
  # Rows are observations resampled by pvclust; columns are clustered ligands.
  
  receptor_ids <- metadata$Receptor[metadata$Species == species_name]
  species_matrix <- score_matrix[receptor_ids, LIGANDS, drop = FALSE]
  
  if (nrow(species_matrix) != expected_receptors ||
      ncol(species_matrix) != 9L) {
    stop("Unexpected matrix dimensions for ", species_name)
  }
  
  # Output filenames retain the original 'Step12A' stem because the Figure 14
  # plotting code previously used these exact edge-table names. Script 05 can
  # therefore read the resulting files without ambiguous renaming.
  
  file_stem <- paste0("Step12A_Ligand_pvclust_", file_label, "_1000000")
  rds_file <- file.path(OUTPUT_DIR, paste0(file_stem, ".rds"))
  edge_file <- file.path(
    OUTPUT_DIR, paste0("Step12A_Ligand_pvclust_Edges_",
                       file_label, "_1000000.csv")
  )
  cluster_file <- file.path(
    OUTPUT_DIR, paste0("Step12A_Ligand_pvclust_Clusters_",
                       file_label, "_1000000.csv")
  )
  diagnostic_pdf <- file.path(OUTPUT_DIR, paste0(file_stem, ".pdf"))
  au90_pdf <- file.path(OUTPUT_DIR, paste0(file_stem, "_AU90_AUonly.pdf"))
  
  expected_cache <- make_cache_details(species_name, species_matrix)
  loaded_from_cache <- FALSE
  pv_result <- NULL
  
  # ---------------------------------------------------------------------------
  # 5.2 REUSE A MATCHING SAVED RESULT, WHEN AVAILABLE
  # ---------------------------------------------------------------------------
  # A successful species run is saved immediately. If a later run is stopped,
  # completing the script a second time reuses earlier completed species.
  
  if (file.exists(rds_file) && !FORCE_RERUN) {
    previous <- tryCatch(readRDS(rds_file), error = function(e) NULL)
    
    if (inherits(previous, "pvclust") &&
        identical(attr(previous, "integrin_cache_details"), expected_cache)) {
      pv_result <- previous
      loaded_from_cache <- TRUE
      message("Reusing validated saved bootstrap: ", species_name)
    } else {
      message("Saved bootstrap is incompatible or unverifiable; rerunning: ",
              species_name)
    }
  }
  
  # ---------------------------------------------------------------------------
  # 5.3 PERFORM THE ORIGINAL 1,000,000-REPLICATE PVCLUST ANALYSIS
  # ---------------------------------------------------------------------------
  # Reset the random seed independently for each species, as in Script2C.R.
  # Parallel computation remains disabled to retain the original settings.
  #
  # pvclust clusters COLUMNS, so species_matrix must NOT be transposed here.
  # The default multiscale factors are specified explicitly for provenance.
  
  if (!loaded_from_cache) {
    message("Running pvclust for ", species_name, " (",
            nrow(species_matrix), " receptors x ",
            ncol(species_matrix), " ligands; ",
            format(NBOOT, big.mark = ",", scientific = FALSE),
            " replicates per scale).")
    
    set.seed(SEED)
    
    pv_result <- pvclust::pvclust(
      species_matrix,
      method.hclust = "complete",
      method.dist = "euclidean",
      nboot = NBOOT,
      r = RESAMPLING_SCALES,
      parallel = FALSE
    )
    
    # Save immediately, before producing secondary tables and figures.
    # This retains the costly bootstrap even if plotting later fails.
    attr(pv_result, "integrin_cache_details") <- expected_cache
    saveRDS(pv_result, rds_file)
    message("Saved completed bootstrap object: ", rds_file)
  }
  
  # ---------------------------------------------------------------------------
  # 5.4 CHECK THAT THE RESULT REPRESENTS THE EXPECTED NINE LIGANDS
  # ---------------------------------------------------------------------------
  
  if (!inherits(pv_result, "pvclust") ||
      !setequal(pv_result$hclust$labels, LIGANDS) ||
      nrow(pv_result$edges) != length(LIGANDS) - 1L ||
      !all(c("au", "bp") %in% names(pv_result$edges))) {
    stop("Invalid/incompatible pvclust result for ", species_name)
  }
  
  # ---------------------------------------------------------------------------
  # 5.5 EXPORT THE FULL EDGE-LEVEL SUPPORT TABLE
  # ---------------------------------------------------------------------------
  # The 'au' and 'bp' columns contain proportions on the 0-1 scale.
  # The added edge column is the node/edge identifier from pvclust.
  # This format remains compatible with the original Figure 14 code.
  
  edge_table <- as.data.frame(pv_result$edges)
  edge_table$edge <- seq_len(nrow(edge_table))
  edge_table <- edge_table[, c("edge", setdiff(names(edge_table), "edge")),
                           drop = FALSE]
  utils::write.csv(edge_table, edge_file, row.names = FALSE)
  
  # Provide an audit-friendly table that identifies which ligands belong to
  # each cluster, alongside their AU and BP support percentages.
  cluster_table <- make_cluster_membership(pv_result)
  utils::write.csv(cluster_table, cluster_file, row.names = FALSE)
  
  # ---------------------------------------------------------------------------
  # 5.6 GENERATE THE TWO ORIGINAL DENDROGRAM FORMATS
  # ---------------------------------------------------------------------------
  
  save_bootstrap_plot(
    pv_result, species_name, diagnostic_pdf,
    DIAGNOSTIC_AU_THRESHOLD, au_only = FALSE
  )
  save_bootstrap_plot(
    pv_result, species_name, au90_pdf,
    REPORTING_AU_THRESHOLD, au_only = TRUE
  )
  
  # The root cluster includes all nine ligands and is omitted from this count.
  # Its AU value is not informative for interpreting selective ligand groups.
  non_root <- seq_len(nrow(cluster_table) - 1L)
  n_supported <- sum(
    cluster_table$AU_Percent[non_root] >= 100 * REPORTING_AU_THRESHOLD,
    na.rm = TRUE
  )
  
  message("Completed ", species_name, "; AU >= 90% non-root clusters: ",
          n_supported, "; saved to ", OUTPUT_DIR)
  
  # Return a small summary, not the full pvclust object: the full results
  # are already preserved in an RDS file for use by Script 05.
  data.frame(
    Species = species_name,
    N_Receptors = nrow(species_matrix),
    N_Ligands = ncol(species_matrix),
    NBOOT_Per_Scale = NBOOT,
    Number_Of_Scales = length(RESAMPLING_SCALES),
    Seed = SEED,
    Reused_Cache = loaded_from_cache,
    NonRoot_Clusters_AU_AtLeast_90Pct = n_supported,
    Pvclust_Version = as.character(utils::packageVersion("pvclust")),
    stringsAsFactors = FALSE
  )
}


# ==============================================================================
# 6. EXECUTE THE ANALYSIS FOR ALL THREE SPECIES
# ==============================================================================

# The loop uses the same helper function and identical clustering settings
# for each species. The only differences are their receptor subsets and sizes.
# Species results are saved independently; no species is pooled or resampled
# together with another species.

summary_parts <- lapply(seq_len(nrow(SPECIES)), function(i) {
  run_species_bootstrap(
    species_name = SPECIES$Name[i],
    file_label = SPECIES$FileLabel[i],
    expected_receptors = SPECIES$ExpectedReceptors[i]
  )
})

bootstrap_summary <- do.call(rbind, summary_parts)
rownames(bootstrap_summary) <- NULL

# Export a machine-readable record of the three completed species analyses.
utils::write.csv(
  bootstrap_summary,
  file.path(OUTPUT_DIR, "LigandCluster_Bootstrap_RunSummary.csv"),
  row.names = FALSE
)

print(bootstrap_summary, row.names = FALSE)
message("All three species-specific ligand bootstrap analyses completed.")
message("Results saved to: ", OUTPUT_DIR)


